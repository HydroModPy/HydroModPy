"""Generate ``catalog.toml`` from the examples of the repository.

The command behind it is ``python -m tools.dev examples manifest``. The
generator finds every example under ``examples/projects/``, resolves each
project's data references the way a run resolves them
(:func:`hydromodpy.core.payload.resolve.project_data`, the resolver of
``hmp publish --package`` too), hashes every file and writes the manifest. It
only runs from a source checkout: a wheel does not carry ``examples/``.

An example is a folder ``<NN>_<name>`` holding a ``project.toml`` and a
``README.md``. Its id is ``NN``. The first heading of the README gives the
title, its first paragraph the summary, and the sentence "A run takes about
..." of that paragraph the runtime. A new example therefore needs no line of
Python: write the folder, run the command, commit the catalog. A test compares
the regenerated bytes with the committed file, so a forgotten regeneration fails
the suite.
"""

from __future__ import annotations

import hashlib
import re
from pathlib import Path

from hydromodpy.core.exceptions import ConfigError
from hydromodpy.core.payload.index import PayloadFile
from hydromodpy.core.payload.resolve import authored_files, project_data
from hydromodpy.project.examples.manifest import ExampleEntry, catalog_path, render_catalog

ENTRY_CONFIG = "project.toml"
"""The config every example starts from, and half of what makes a folder an example."""

_FOLDER_RE = re.compile(r"^\d{2}_\w+$")
_TITLE_PREFIX_RE = re.compile(r"^Example\s+\d+\s*:\s*", re.IGNORECASE)
_RUNTIME_RE = re.compile(r"A run takes (?P<runtime>[^.]+)\.")


def repo_root() -> Path:
    """Return the checkout root, found by walking up to ``examples/projects/``."""
    for parent in Path(__file__).resolve().parents:
        if (parent / "examples" / "projects").is_dir():
            return parent
    raise ConfigError(
        "No examples/projects/ above this module. The manifest generator runs "
        "from a source checkout, not from an installed wheel."
    )


def example_folders(root: Path) -> list[Path]:
    """Return the example folders under ``examples/projects/``, sorted by name.

    A folder without a ``README.md`` is a working folder, not an example, and
    stays out. That is how a scratch project kept beside the examples on one
    machine never reaches the catalog.
    """
    projects = root / "examples" / "projects"
    return sorted(
        folder
        for folder in projects.iterdir()
        if folder.is_dir()
        and _FOLDER_RE.match(folder.name)
        and (folder / ENTRY_CONFIG).is_file()
        and (folder / "README.md").is_file()
    )


def build_catalog(root: Path | None = None) -> tuple[ExampleEntry, ...]:
    """Build one entry per example folder, hashing each file it names."""
    base = root if root is not None else repo_root()
    entries = tuple(_build_entry(folder, base) for folder in example_folders(base))
    _refuse_clashes(entries)
    return entries


def write_catalog(
    root: Path | None = None,
    destination: Path | None = None,
) -> tuple[Path, tuple[ExampleEntry, ...]]:
    """Render the catalog and write it, returning the path and the entries.

    The entries come back with it so a caller that wants to report what was
    written does not hash a 90 MiB DEM a second time to find out.
    """
    entries = build_catalog(root)
    target = destination if destination is not None else catalog_path()
    target.write_text(render_catalog(entries), encoding="utf-8")
    return target, entries


def read_readme(readme: Path) -> tuple[str, str, str]:
    """Return the title, the summary and the runtime a README gives.

    The title is the first ``# `` heading without its "Example NN:" prefix. The
    summary is the first paragraph after it, on one line. The runtime is what
    follows "A run takes" in that paragraph, up to the full stop.
    """
    lines = readme.read_text(encoding="utf-8").splitlines()
    heading = next((i for i, line in enumerate(lines) if line.startswith("# ")), None)
    if heading is None:
        raise ConfigError(f"{readme} has no '# ' heading to take the example title from.")
    title = _TITLE_PREFIX_RE.sub("", lines[heading][2:].strip())
    title = title[:1].upper() + title[1:]

    paragraph: list[str] = []
    for line in lines[heading + 1 :]:
        if line.strip():
            paragraph.append(line.strip())
        elif paragraph:
            break
    summary = " ".join(paragraph)
    match = _RUNTIME_RE.search(summary)
    if not summary or match is None:
        raise ConfigError(
            f"{readme}: the first paragraph after the title is the summary of the "
            f"example, and it has to say how long a run takes, as 'A run takes about 40 s.'"
        )
    return title, summary, match.group("runtime").strip()


def _build_entry(project_dir: Path, root: Path) -> ExampleEntry:
    from hydromodpy.config.hydromodpy_config import ROOT_CONFIG

    title, summary, runtime = read_readme(project_dir / "README.md")
    authored = [
        _describe(root, path, f"projects/{project_dir.name}/{path.name}")
        for path in authored_files(project_dir)
    ]
    data_files, stations = project_data(project_dir, root / "examples" / "data", root=ROOT_CONFIG)
    data = [_describe(root, path, f"data/{path.parent.name}/{path.name}") for path in data_files]
    return ExampleEntry(
        id=project_dir.name.split("_", 1)[0],
        directory=project_dir.name,
        title=title,
        summary=summary,
        runtime=runtime,
        entry_config=ENTRY_CONFIG,
        files=tuple(sorted(authored, key=lambda item: item.dest)),
        data=tuple(sorted(data, key=lambda item: item.dest)),
        stations=stations,
    )


def _refuse_clashes(entries: tuple[ExampleEntry, ...]) -> None:
    """Refuse two examples that put different content at one place of a workspace.

    ``hmp example add --all`` writes every example into one workspace, so a
    shared data file must be the same file, and a shared id the same example.
    """
    seen_ids: dict[str, str] = {}
    seen_files: dict[str, tuple[str, str]] = {}
    seen_rows: dict[tuple[str, str], tuple[str, tuple[tuple[str, str], ...]]] = {}
    for entry in entries:
        if entry.id in seen_ids:
            raise ConfigError(
                f"Examples {seen_ids[entry.id]} and {entry.directory} share the id {entry.id}."
            )
        seen_ids[entry.id] = entry.directory
        for item in entry.payload:
            first = seen_files.setdefault(item.dest, (entry.id, item.sha256))
            if first[1] != item.sha256:
                raise ConfigError(
                    f"Examples {first[0]} and {entry.id} both install {item.dest} "
                    f"with different content. Give one of the files another name."
                )
        for station in entry.stations:
            key = (station.dest, station.id)
            first_row = seen_rows.setdefault(key, (entry.id, station.row))
            if first_row[1] != station.row:
                raise ConfigError(
                    f"Examples {first_row[0]} and {entry.id} both register station "
                    f"{station.id} in {station.dest} with different values."
                )


def _describe(root: Path, path: Path, dest: str) -> PayloadFile:
    payload = path.read_bytes()
    return PayloadFile(
        repo_path=path.relative_to(root).as_posix(),
        dest=dest,
        size=len(payload),
        sha256=hashlib.sha256(payload).hexdigest(),
    )
