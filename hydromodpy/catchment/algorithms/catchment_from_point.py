"""Delineate a catchment polygon from one outlet coordinate.

Purpose
-------
Transform one configured outlet point into canonical watershed products
(``outlet.shp``, ``outlet_snap.shp``, ``watershed.tif``, ``watershed.shp``).

Pipeline position
-----------------
Used when ``catch_def='from_outlet_coord'`` in the geographic workflow.

Processing steps
----------------
1. Build a point layer from ``x_outlet`` / ``y_outlet``.
2. Snap the point inside its window: to the strongest flow cell of the window
   (``window``) or to the nearest cell of the extracted stream network (``jenson``).
3. Run watershed delineation from D8 direction raster.
4. Polygonize the resulting watershed raster for downstream GIS/domain usage.

Why this file computes nothing
------------------------------
All four steps belong to :meth:`TerrainEngine.delineate
<hydromodpy.catchment.terrain.port.TerrainEngine.delineate>`. What stays here is the
one thing the engine has no business knowing: this pipeline publishes its
catchment as ``watershed.tif`` and ``watershed.shp``, flat in a directory that
twenty other artifacts share, and every golden in the tree reads them there.
That shape is passed to the engine as a
:class:`~hydromodpy.catchment.terrain.port.CatchmentLayout`.

Import and normalize an externally provided catchment polygon.

Purpose
-------
Support workflows where catchment delineation is already available outside
HydroModPy and only needs to be standardized for internal pipeline contracts.

Pipeline position
-----------------
Used when ``catch_def='from_polyg_shp'`` in the geographic workflow.

Main responsibilities
---------------------
- copy the input polygon to canonical ``watershed.shp`` location,
- remove duplicate attribute columns often found in shapefile exports,
- enforce CRS metadata expected by downstream steps.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Literal

import geopandas as gpd

from hydromodpy.catchment.algorithms.flow_products import (
    jenson_snap_from_threshold,
    rankable_accumulation,
)
from hydromodpy.catchment.terrain import registry as terrain_registry
from hydromodpy.catchment.terrain.port import (
    OUTLET_LAYER_NAME,
    SNAPPED_OUTLET_LAYER_NAME,
    CatchmentLayout,
    FlowAccumulation,
    Outlet,
    SnapMethod,
)
from hydromodpy.core.console import progress
from hydromodpy.core.exceptions import TerrainProductError
from hydromodpy.core.io.crs import ensure_crs
from hydromodpy.core.logging import get_logger


def write_shapefile_without_duplicate_columns(src_path: str | Path, dst_path: str | Path) -> None:
    """Read a shapefile and write it back after dropping duplicate column names."""
    gdf = gpd.read_file(src_path)
    gdf = gdf.loc[:, ~gdf.columns.duplicated()]
    gdf.to_file(dst_path)


logger = get_logger(__name__)

WATERSHED_TIF_NAME = "watershed.tif"
WATERSHED_SHP_NAME = "watershed.shp"

CATCHMENT_LAYOUT = CatchmentLayout.flat(
    mask_name=WATERSHED_TIF_NAME,
    boundary_name=WATERSHED_SHP_NAME,
)
"""The on-disk shape this pipeline has always published, now declared.

Flat rather than one directory per outlet, because ``GeographicPaths`` names
``watershed.tif`` and ``watershed.shp`` inside ``geographic/`` and moving them
would move every golden that reads them.
"""

OUTLET_ID = "outlet"
"""The name the engine puts in its refusals; a flat layout has no directory."""


@dataclass(frozen=True)
class CatchmentFromPointProducts:
    """Paths to all artifacts generated by outlet-based delineation."""

    outlet_shp: str
    outlet_snap_shp: str
    watershed_tif: str
    watershed_shp: str
    x_outlet_snapped: float | None = None
    """X the delineation actually ran from, after the snap moved the declared point.

    None when the products were not produced by an outlet snap, which is why the
    three snap fields carry a default: not every construction path snaps.
    """

    y_outlet_snapped: float | None = None
    """Y the delineation actually ran from, after the snap moved the declared point."""

    snap_distance_m: float | None = None
    """Distance the snap moved the outlet. The declared coordinate is not the one used."""


def extract_catchment_from_point(
    *,
    x_outlet: float,
    y_outlet: float,
    snap_dist: int,
    accumulation: FlowAccumulation,
    output_dir: str | Path,
    crs_project: str | None = None,
    backend: object | None = None,
    engine_id: str | None = None,
    snap_method: Literal["window", "jenson"] = "window",
    stream_threshold_cells: float | None = None,
) -> CatchmentFromPointProducts:
    """Delineate a catchment polygon from one outlet point.

    Parameters
    ----------
    x_outlet, y_outlet:
        Outlet coordinates in model projected CRS.
    snap_dist:
        Width of the square snap window, in map units, for both snap methods.
        Not a maximum displacement: a value equal to one cell size snaps nowhere,
        and 100 m on a 25 m grid can move an outlet 70.7 m diagonally.
    accumulation:
        The regional accumulation to snap against, with the pointer it was
        derived from. Both are the engine's own products.
    output_dir:
        Folder where output files are written.
    crs_project:
        Optional CRS enforced on generated files, on top of the one the engine
        carries from the source DEM.
    backend:
        Optional Whitebox backend for runtime/tests. It reaches the engine only
        if that engine names ``backend`` in its constructor.
    engine_id:
        Name of the terrain engine to delineate with. ``None`` resolves the
        default this build ships.
    snap_method:
        ``window`` moves the outlet to the largest accumulation of its window.
        ``jenson`` moves it to the nearest cell of the stream network drawn from
        the pointer of ``accumulation``, and refuses an outlet with none in its
        window.
    stream_threshold_cells:
        Upstream cell count above which a cell is a stream cell. Required by
        ``jenson`` and refused by ``window``, which has no network to draw.
    """
    if snap_method not in ("window", "jenson"):
        raise ValueError(f"Unknown snap_method {snap_method!r}. Expected 'window' or 'jenson'.")
    if (snap_method == "jenson") != (stream_threshold_cells is not None):
        raise ValueError(
            "stream_threshold_cells goes with snap_method='jenson', and only with it: "
            f"got snap_method={snap_method!r} and stream_threshold_cells={stream_threshold_cells!r}."
        )
    engine = terrain_registry.terrain_engines.create(engine_id, backend=backend)
    out_dir = Path(output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    snap: SnapMethod
    if snap_method == "jenson":
        with progress.status("Extracting the stream network to snap onto"):
            snap = jenson_snap_from_threshold(
                engine,
                accumulation,
                threshold_cells=float(stream_threshold_cells),
                out_dir=out_dir,
            )
    else:
        snap = "window"
        # A basin beyond the float32 ln range is ranked on raw counts instead.
        accumulation = rankable_accumulation(
            engine,
            accumulation,
            [(float(x_outlet), float(y_outlet))],
            snap_distance_m=float(snap_dist),
            out=out_dir / "dem_acc_cells_for_snap.tif",
        )

    with progress.status("Delineating watershed"):
        try:
            (catchment,) = engine.delineate(
                accumulation,
                [Outlet(outlet_id=OUTLET_ID, x=float(x_outlet), y=float(y_outlet))],
                out_dir=out_dir,
                snap_distance_m=float(snap_dist),
                snap=snap,
                layout=CATCHMENT_LAYOUT,
            )
        except TerrainProductError as exc:
            # The engine knows rasters and windows; only this layer knows which
            # configuration keys the user would have to change. Re-raised as its
            # own class and not as the base one: a caller that decides on
            # EmptyCatchmentError would stop seeing it if the type were widened
            # here.
            lower_threshold = (
                " or lower the threshold of geographic.river_network, which draws the "
                "stream network the outlet snaps onto"
                if snap_method == "jenson"
                else ""
            )
            raise type(exc)(
                f"{exc} Check geographic.catchment.x_outlet / y_outlet, increase "
                f"geographic.catchment.snap_dist,{lower_threshold} or verify that the "
                "corrected DEM and flow-accumulation rasters cover the outlet."
            ) from exc

    outlet_shp = out_dir / OUTLET_LAYER_NAME
    outlet_snap_shp = out_dir / SNAPPED_OUTLET_LAYER_NAME
    for path in (outlet_shp, outlet_snap_shp, catchment.mask_path, catchment.boundary_path):
        ensure_crs(path, crs_project)

    # The declared coordinate is what every report shows; say how far the
    # delineation actually started from it, because nothing downstream can tell.
    log = logger.warning if catchment.snap_distance_m > 0.5 * float(snap_dist) else logger.info
    log(
        "Outlet moved %.0f m (limit %.0f m) onto the flow network, "
        "from (%.0f, %.0f) to (%.0f, %.0f).",
        catchment.snap_distance_m,
        float(snap_dist),
        x_outlet,
        y_outlet,
        catchment.snapped_x,
        catchment.snapped_y,
    )

    return CatchmentFromPointProducts(
        outlet_shp=str(outlet_shp),
        outlet_snap_shp=str(outlet_snap_shp),
        watershed_tif=str(catchment.mask_path),
        watershed_shp=str(catchment.boundary_path),
        x_outlet_snapped=catchment.snapped_x,
        y_outlet_snapped=catchment.snapped_y,
        snap_distance_m=catchment.snap_distance_m,
    )


def extract_catchment_from_polygon(
    *,
    polyg_shp_path: str | Path,
    output_shp_path: str | Path,
    crs_project: str | None = None,
) -> str:
    """Copy and sanitize one input catchment polygon shapefile.

    Parameters
    ----------
    polyg_shp_path:
        Source catchment polygon path.
    output_shp_path:
        Canonical destination path (usually ``watershed.shp``).
    crs_project:
        Optional CRS override to enforce on output metadata.

    Returns
    -------
    str
        Path to the sanitized output shapefile.
    """
    src = Path(polyg_shp_path)
    dst = Path(output_shp_path)
    if not src.exists():
        raise FileNotFoundError(f"polyg_shp_path not found: {src}")
    dst.parent.mkdir(parents=True, exist_ok=True)

    # Keep schema stable by dropping duplicate column names.
    write_shapefile_without_duplicate_columns(src, dst)

    # Enforce output CRS metadata when requested by caller.
    ensure_crs(dst, crs_project)
    return str(dst)
