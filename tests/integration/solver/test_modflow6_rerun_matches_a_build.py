"""A MODFLOW 6 rerun for a new K or Sy is bit-identical to a build of the same ``Model``.

An island is prepared by the real steps up to the ``Model`` of its flow run, once
steady (the form of the calibration reference) and once transient over twelve
months, with drains whose conductance follows K. For each case a first run is
built and solved, the ``Model`` gets a new K, a new Sy or both through
``with_properties``, and the change is solved twice under the same run name in
two folders: once by a new build, once by ``rerun`` from the first run.

Bit-identical means four things. The input files are equal once the line
FloPy stamps with a date is set aside. The head, budget and grid files MODFLOW 6
writes are equal byte for byte. The file of the properties holds equal arrays.
The fields and tables the extractor writes into a store are equal.
"""

from __future__ import annotations

import os
from collections.abc import Iterator
from pathlib import Path
from typing import Any

import numpy as np
import pytest
import zarr

from hydromodpy.core.budget.terms import BudgetKeep
from hydromodpy.results.storage.kept import Retention
from hydromodpy.solver.base.plan import RunSlot, SolverRun
from hydromodpy.solver.base.runner import solve_one
from hydromodpy.solver.modflow6.adapter import Modflow6FlowAdapter
from tests._helpers.island_project import island_toml
from tests._helpers.run_stores import open_run_store

pytestmark = [
    pytest.mark.integration,
    pytest.mark.mf6,
    pytest.mark.binary,
    pytest.mark.allow_subprocess,
]

K_M_S = 5e-6
FLOPY_HEADER = "# File generated by Flopy"
TRANSIENT = (
    ('types = ["oceanic", "recharge"]', 'types = ["oceanic"]'),
    ('[[data.recharge.sources]]\nsource = "synthetic"\nvalues = [1.0]\n', ""),
    ('flow_regime = "steady"', 'flow_regime = "transient"'),
    ('param_list = ["K"]', 'param_list = ["K", "Sy", "Ss"]'),
    (
        'start_datetime = "2003-01-01 00:00:00"\n'
        'end_datetime = "2003-01-02 00:00:00"\n'
        'step_value = "1 day"\n',
        'start_datetime = "2003-01-01"\nend_datetime = "2003-12-31"\nstep_value = "1 month"\n',
    ),
    (
        'first_clim = "mean"',
        "values = [1.0, 1.5, 2.0, 0.5, 0.2, 0.0, 0.0, 0.1, 0.5, 1.5, 2.0, 2.5]",
    ),
)
STORAGE = """
[flow.param.Sy.field]
kind = "homogeneous"
unit = "-"
value = 0.1

[flow.param.Ss.field]
kind = "homogeneous"
unit = "m-1"
value = 1e-5

[flow.ic]
kind = "top"
"""


def _prepare(root: Path, *, transient: bool) -> Any:
    """Run the steps of an island run up to the ``Model`` of its flow, and return the context."""
    from hydromodpy.core.time import require_flow_simulation_time_grid
    from hydromodpy.workflow.state import PipelineState
    from hydromodpy.workflow.steps.sequence import standard_steps

    text = island_toml("rerun")
    if transient:
        for old, new in TRANSIENT:
            assert old in text, old
            text = text.replace(old, new)
        text += STORAGE
    root.mkdir(parents=True)
    config = root / "project.toml"
    config.write_text(text, encoding="utf-8")
    state = PipelineState(run_id="rerun", data={"config_path": config})
    for step in standard_steps():
        if step.name == "run_solver":
            break
        state = step.run(state)
        if step.name == "resolve":
            # A project resolves the time grid before its steps, as Project does.
            ctx = state.data["ctx"]
            ctx.setup.time_grid = require_flow_simulation_time_grid(ctx.cfg)
    return state.data["ctx"]


@pytest.fixture(scope="module")
def islands(tmp_path_factory: pytest.TempPathFactory) -> Iterator[dict[str, Any]]:
    """The steady and the transient island, prepared once for every case."""
    root = tmp_path_factory.mktemp("rerun_islands")
    here = Path.cwd()
    try:
        os.chdir(root)
        yield {
            "steady": _prepare(root / "steady", transient=False),
            "transient": _prepare(root / "transient", transient=True),
        }
    finally:
        os.chdir(here)


def _solve(ctx: Any, model: Any, folder: Path, *, previous: SolverRun | None = None) -> SolverRun:
    """Solve ``model`` under the run name ``island`` in ``folder``, from ``previous`` if given."""
    options = ctx.cfg.solver.options_of("modflow6")
    slot = RunSlot(folder, "island", bin_dir=ctx.setup.workspace.bin_path)
    return solve_one(Modflow6FlowAdapter(), model, options, slot, previous=previous)


def _text_without_the_flopy_stamp(path: Path) -> list[str] | None:
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except UnicodeDecodeError:
        return None
    return [line for line in lines if not line.startswith(FLOPY_HEADER)]


def _same_file(left: Path, right: Path) -> bool:
    if left.suffix == ".npz":
        with np.load(left) as a, np.load(right) as b:
            return sorted(a.files) == sorted(b.files) and all(
                np.array_equal(a[name], b[name]) for name in a.files
            )
    text = _text_without_the_flopy_stamp(left)
    if text is not None:
        return text == _text_without_the_flopy_stamp(right)
    return left.read_bytes() == right.read_bytes()


def _extracted(solver_run: SolverRun, project: Path) -> dict[str, np.ndarray]:
    """Every array the extractor writes into the field store of a new run."""
    solver = solver_run.solver_model
    store = open_run_store(project, "run", n_cells=int(solver.ncpl), n_layers=int(solver.nlay))
    try:
        Modflow6FlowAdapter().extract(
            solver_run, store, Retention(budget=BudgetKeep.everything(), solver_files=True)
        )
    finally:
        store.close()
    arrays: dict[str, np.ndarray] = {}
    root = zarr.open_group(str(store.fields_path), mode="r")

    def walk(group: Any, prefix: str) -> None:
        for name, item in group.members():
            if isinstance(item, zarr.Group):
                walk(item, f"{prefix}{name}/")
            else:
                arrays[f"{prefix}{name}"] = np.asarray(item[...])

    walk(root, "")
    return arrays


def _assert_bit_identical(built: SolverRun, rerun: SolverRun, tmp_path: Path) -> None:
    assert rerun.slot.name == built.slot.name
    assert sorted(rerun.input_files) == sorted(built.input_files)
    different_inputs = [
        name
        for name in built.input_files
        if not _same_file(built.output_dir / name, rerun.output_dir / name)
    ]
    assert different_inputs == [], "input files differ"
    outputs = sorted(
        path.name
        for pattern in ("*.hds", "*.cbc", "*.grb")
        for path in built.output_dir.glob(pattern)
    )
    assert any(name.endswith(".hds") for name in outputs)
    assert any(name.endswith(".cbc") for name in outputs)
    for name in outputs:
        assert (built.output_dir / name).read_bytes() == (rerun.output_dir / name).read_bytes(), (
            name
        )
    (properties,) = built.output_dir.glob("*.flow_properties.npz")
    assert _same_file(properties, rerun.output_dir / properties.name)
    left = _extracted(built, tmp_path / "store_built")
    right = _extracted(rerun, tmp_path / "store_rerun")
    assert sorted(left) == sorted(right)
    assert "head" in left
    for name, values in left.items():
        np.testing.assert_array_equal(values, right[name], err_msg=name)


CASES = (
    ("steady island, K alone", "steady", {"K": 3.0 * K_M_S}, (1, 0)),
    (
        "transient island, K alone with drains that follow it",
        "transient",
        {"K": 3.0 * K_M_S},
        (1, 0),
    ),
    ("transient island, Sy alone", "transient", {"Sy": 0.2}, (0, 1)),
    ("transient island, K and Sy", "transient", {"K": 0.5 * K_M_S, "Sy": 0.05}, (1, 1)),
)


@pytest.mark.parametrize(
    ("case", "island", "properties", "rewritten"), CASES, ids=[case[0] for case in CASES]
)
def test_a_rerun_matches_a_build_of_the_same_model(
    islands: dict[str, Any],
    tmp_path: Path,
    case: str,
    island: str,
    properties: dict[str, float],
    rewritten: tuple[int, int],
) -> None:
    del case
    ctx = islands[island]
    base = ctx.setup.model
    changed = base.with_properties(**properties)

    first = _solve(ctx, base, tmp_path / "first")
    built = _solve(ctx, changed, tmp_path / "built")
    stamps = {
        name: (first.output_dir / name).stat().st_mtime_ns
        for name in first.input_files
        if name.endswith((".npf", ".sto", ".drn"))
    }
    rerun = _solve(ctx, changed, tmp_path / "rerun", previous=first)

    assert rerun.solver_model is first.solver_model, "the rerun took the solver object over"
    assert built.solver_model is not first.solver_model
    assert (rerun.written, rerun.solved) == (True, True)
    _assert_bit_identical(built, rerun, tmp_path)
    npf_rewritten = any(
        (rerun.output_dir / name).stat().st_mtime_ns != stamp
        for name, stamp in stamps.items()
        if name.endswith(".npf")
    )
    sto_rewritten = any(
        (rerun.output_dir / name).stat().st_mtime_ns != stamp
        for name, stamp in stamps.items()
        if name.endswith(".sto")
    )
    assert (int(npf_rewritten), int(sto_rewritten)) == rewritten


def test_the_drains_of_the_transient_island_follow_k(
    islands: dict[str, Any], tmp_path: Path
) -> None:
    """The transient case holds a DRN that K reaches, or it would prove less than it says."""
    first = _solve(islands["transient"], islands["transient"].setup.model, tmp_path / "first")

    assert first.solver_model.drn is not None
    assert first.solver_model._drainage_uses_hk is True


def test_a_chain_of_reruns_matches_a_build_of_its_last_model(
    islands: dict[str, Any], tmp_path: Path
) -> None:
    ctx = islands["transient"]
    base = ctx.setup.model
    with_k = base.with_properties(K=2.0 * K_M_S)
    with_k_and_sy = with_k.with_properties(K=2.0 * K_M_S, Sy=0.3)

    first = _solve(ctx, base, tmp_path / "first")
    second = _solve(ctx, with_k, tmp_path / "second", previous=first)
    third = _solve(ctx, with_k_and_sy, tmp_path / "third", previous=second)
    built = _solve(ctx, with_k_and_sy, tmp_path / "built")

    assert third.solver_model is first.solver_model
    _assert_bit_identical(built, third, tmp_path)


def test_a_steady_start_builds_instead_of_rerunning(
    islands: dict[str, Any], tmp_path: Path
) -> None:
    """A start from a steady solve depends on K, so the runner builds and the parent stays."""
    from hydromodpy.model.initial.state import SteadyStart

    ctx = islands["transient"]
    base = ctx.setup.model.with_initial(SteadyStart())
    changed = base.with_properties(K=3.0 * K_M_S)

    first = _solve(ctx, base, tmp_path / "first")
    second = _solve(ctx, changed, tmp_path / "second", previous=first)

    assert second.solver_model is not first.solver_model
    assert first.solver_model.inputs is base
    assert second.solved is True
