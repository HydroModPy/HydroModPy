"""Writing a configuration to TOML and reading it back gives the same values."""

from __future__ import annotations

import tomllib
from pathlib import Path
from typing import Annotated

import pytest
from pydantic import Field

from hydromodpy.core.config_kit import dump as dumper
from hydromodpy.core.config_kit.base import HydroModelBase
from hydromodpy.core.config_kit.dump import dump_toml_with_comments
from hydromodpy.core.config_kit.profile import Profile


class _Aquifer(HydroModelBase):
    dem: Path = Path("dem.tif")
    k: float = Field(default=1e-5, description="Hydraulic conductivity in m/s.\nSecond line.")
    layers: int = 1


class _Well(HydroModelBase):
    name: str
    q: float = 0.0


class _Cfg(HydroModelBase):
    title: Annotated[str, Profile.USER] = Field(default="demo", description="Run title.")
    aquifer: _Aquifer = _Aquifer()
    wells: list[_Well] = []
    tags: tuple[str, ...] = ()
    limits: dict[str, float] = {}
    data_dir: Path = Path("data")
    note: str | None = None
    solver_tol: Annotated[float, Profile.DEV] = 1e-6
    pcg: Annotated[float, Profile.EXPERT] = 0.97
    internal: Annotated[str, Field(json_schema_extra={"toml_exclude": True})] = "hidden"


def _load(path: Path) -> dict:
    return tomllib.loads(path.read_text(encoding="utf-8"))


def test_the_description_of_a_field_is_kept_as_a_comment_on_its_line(tmp_path: Path) -> None:
    path = dump_toml_with_comments(_Cfg(), tmp_path / "c.toml")
    text = path.read_text(encoding="utf-8")
    assert "# Hydraulic conductivity in m/s." in text
    assert "Second line" not in text
    assert text.startswith("# Generated by")
    assert "profile = 'user'" in text


def test_an_unknown_profile_is_refused(tmp_path: Path) -> None:
    with pytest.raises(ValueError, match="Unknown profile 'guru'"):
        dump_toml_with_comments(_Cfg(), tmp_path / "c.toml", profile="guru")  # type: ignore[arg-type]


def test_to_toml_on_a_model_writes_the_same_file(tmp_path: Path) -> None:
    cfg = _Cfg(title="t")
    assert (
        cfg.to_toml(tmp_path / "a.toml").read_text()
        == dump_toml_with_comments(cfg, tmp_path / "b.toml").read_text()
    )


class _Meter:
    def __format__(self, spec: str) -> str:
        return "m" if spec == "~" else "meter"


class _Unit:
    magnitude = 2.5
    units = _Meter()


@pytest.mark.parametrize(
    ("value", "expected"),
    [
        (Path("a/b"), str(Path("a/b"))),
        (_Unit(), "2.5 m"),
        ((Path("a"), 1), ["a", 1]),
        ([(1, 2)], [[1, 2]]),
        (3, 3),
    ],
)
def test_a_value_is_turned_into_something_toml_can_hold(value, expected) -> None:
    assert dumper._coerce_value(value) == expected


def test_a_list_mixing_tables_and_scalars_is_refused() -> None:
    mixed = [_Well(name="w"), 3]
    with pytest.raises(TypeError, match="Mixed scalar and table"):
        dumper._render_container_value(mixed, profile_threshold=Profile.USER)


def test_a_list_skips_its_none_items() -> None:
    rendered = dumper._render_container_value([1, None, 2], profile_threshold=Profile.USER)
    assert list(rendered) == [1, 2]
