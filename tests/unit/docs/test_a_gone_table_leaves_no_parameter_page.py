"""A table that leaves the models leaves no page in the parameter reference.

The pages under ``reference/parameters`` are generated and ignored by git, so
a stale page stays on disk until the generator deletes it. A stale page whose
directive names a gone table stopped every build from 2026-10-16.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

EXT = Path(__file__).resolve().parents[3] / "docs" / "source" / "_ext"
MARK = "% AUTO-GENERATED by _ext/hmp_tview.py from the models. Do not edit.\n"


@pytest.fixture(scope="module")
def T():
    """hmp_tview is a module of docs/source/_ext, not of a package."""
    sys.path.insert(0, str(EXT))
    import hmp_tview

    yield hmp_tview
    sys.path.remove(str(EXT))


def test_only_the_stale_generated_pages_go(T, tmp_path: Path) -> None:
    base = tmp_path / "reference" / "parameters"
    (base / "analysis").mkdir(parents=True)
    written = base / "mesh.md"
    stale = base / "testbed.md"
    stale_split = base / "analysis" / "index.md"
    hand = base / "grammar.md"
    for path in (written, stale, stale_split):
        path.write_text("# Page\n\n" + MARK, encoding="utf-8")
    hand.write_text("# Grammar\n", encoding="utf-8")

    T.drop_stale_pages(base, {written})

    assert written.is_file()
    assert hand.is_file()
    assert not stale.exists()
    assert not (base / "analysis").exists()
