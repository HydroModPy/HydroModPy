"""Lakes, a cutoff wall, a barrier, streams and wells, solved and written to the store.

Three projects play the lake family of MODFLOW 6.

The first is the island of the lake, its cutoff wall and its barrier, stopped
before the solve and played in the process of pytest. The inputs it hands to the
solver are hashed, because a change in the mesh, in the LAK package or in the HFB
package is a change of the model, and the digests below tell it bit for bit.

The second is the same island solved through the command line for three monthly
periods, with a pumping well. The series it stores are held against the
registry: every simulated variable has a descriptor and the unit of the
descriptor, the lake writes ``lake_storage`` and no ``storage``, and the storage
term follows the change of the lake volume with the sign the descriptor gives.

The third is the valley of the Cheze, the lake ``res0`` that its stream network
flows into, two wells, evapotranspiration and a barrier, solved for thirty days.
Its stream series are registered, and its wells pump what the project wrote.
"""

