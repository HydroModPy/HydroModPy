import tomllib
from dataclasses import replace
from pathlib import Path

import numpy as np
import pandas as pd
import pytest

from hydromodpy.results.field_registry import FIELD_REGISTRY, TIME_SERIES_REGISTRY
from hydromodpy.results.storage.contract import PARQUET_FILE_SUFFIX, TABLES_DIRNAME
from hydromodpy.results.storage.udunits import udunits_spelling
from tests.scenarios.factory import cheze_valley_files, lake_island_files, write_project
from tests.scenarios.launcher import Scenario, play

REPO_ROOT = Path(__file__).resolve().parents[2]
CHEZE_DATA = REPO_ROOT / "tests" / "data" / "sfr_cheze"
"""The committed fixture of the valley: a raster, the lake polygon and its abacus."""

MF6_FILES = ("mf6", "libmf6.so")
LAKE_STATION = "lake:reservoir"
"""The station of the island lake, ``lake:<id>`` with the id of its polygon."""

