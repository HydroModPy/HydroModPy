def _sha256_of(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _sha256_without_flopy_header(path: Path) -> str:
    """The digest of a flopy text file without its generated-header lines (E32)."""
    lines = [
        line
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines()
        if "File generated by Flopy" not in line
    ]
    return hashlib.sha256(("\n".join(lines) + "\n").encode("utf-8")).hexdigest()


def _write_binary_inputs(folder: Path) -> None:
    """Write the lake bathymetry and the barrier, the two inputs a text factory cannot hold."""
    import geopandas as gpd
    import rasterio
    from rasterio.transform import from_origin
    from shapely.geometry import LineString

    folder.mkdir(parents=True, exist_ok=True)
    rows, cols = 9, 11
    yy, xx = np.mgrid[0:rows, 0:cols]
    depth = np.clip(0.5 * (1.0 - ((yy - 4.0) / 4.0) ** 2 - ((xx - 5.0) / 5.0) ** 2), 0.05, None)
    bed = 10.0 - depth

    with rasterio.open(
        folder / "lake_bathymetry.tif",
        "w",
        driver="GTiff",
        height=rows,
        width=cols,
        count=1,
        dtype="float64",
        crs="EPSG:2154",
        transform=from_origin(260.0, 340.0, 100.0 / cols, 80.0 / rows),
    ) as dst:
        dst.write(bed, 1)

    trace_ = LineString([(480.0, 200.0), (480.0, 420.0)])
    gpd.GeoDataFrame({"id": ["dam"]}, geometry=[trace_], crs="EPSG:2154").to_file(
        folder / "barrier.gpkg", driver="GPKG"
    )


def _prepare_inputs(root: Path) -> None:
    """Write the default lake island under ``root``, binary inputs under ``inputs/``."""
    write_project(root, lake_island_files())
    _write_binary_inputs(root / "inputs")


def test_lake_and_wall_inputs_hold_still(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """Verify bit-for-bit equivalence of generated lak, hfb, and mesh outputs.

    The run stops before the solve (``RunSlot.stop_before_solve``) and plays in
    this process, because the digests are taken from files the solve never reads.
    """
    import hydromodpy.solver.base.runner as runner_module
    from hydromodpy.project.facade import Project

    _prepare_inputs(tmp_path)
    monkeypatch.chdir(tmp_path)

    orig_solve_one = runner_module.solve_one

    def _patched_solve_one(adapter, model, options, slot, upstream=(), **kwargs):
        slot = replace(slot, stop_before_solve=True)
        res = orig_solve_one(adapter, model, options, slot, upstream, **kwargs)
        if hasattr(res.solver_model, "sim"):
            res.solver_model.sim.write_simulation(silent=True)
        return res

    monkeypatch.setattr(runner_module, "solve_one", _patched_solve_one)

    proj = Project(tmp_path / "project.toml", no_display=True)
    try:
        proj.simulate(until_step="run_solver")
    finally:
        proj.close()

    solver_candidates = sorted((tmp_path / "runs").glob("*/.hmp/scratch/*")) + sorted(
        (tmp_path / "runs").glob("*/solver/*")
    )
    assert solver_candidates, "No solver directory generated"
    solver_dir = solver_candidates[0]

    digests: dict[str, str] = {}
    for suffix, key in (
        (".lak", "lak"),
        (".hfb", "hfb"),
        (".disv", "disv"),
    ):
        matches = sorted(solver_dir.glob(f"*{suffix}"))
        assert matches, f"Missing {suffix} file in {solver_dir}"
        digests[key] = _sha256_without_flopy_header(matches[0])

    mesh_cache = tmp_path / ".hmp" / "products"
    assert mesh_cache.is_dir(), "No stored mesh found"
    npz_matches = sorted(mesh_cache.glob("??/*/mesh.npz"))
    assert npz_matches, "Missing mesh.npz"
    digests["mesh_npz"] = _sha256_of(npz_matches[0])

    json_matches = sorted(mesh_cache.glob("??/*/mesh.json"))
    assert json_matches, "Missing mesh.json"
    digests["mesh_json"] = _sha256_of(json_matches[0])

    for key, expected_digest in BASE_DIGESTS.items():
        actual = digests.get(key)
        assert actual == expected_digest, (
            f"Digest mismatch for {key}: {actual} != {expected_digest}"
        )


def _run_folder(played) -> Path:
    runs = [played.root / path for kind, path in played.targets if kind == "run"]
    assert len(runs) == 1, f"{len(runs)} runs found, the log ends: {played.log.read_text()[-1500:]}"
    return runs[0]


def _simulated_series(run_dir: Path) -> pd.DataFrame:
    """Return the simulated rows of ``timeseries.parquet``, sorted by station and step."""
    table = pd.read_parquet(run_dir / TABLES_DIRNAME / f"timeseries{PARQUET_FILE_SUFFIX}")
    rows = table[table["source"] == "simulated"]
    return rows.sort_values(["station_id", "variable", "timestep"]).reset_index(drop=True)


def _registered_unit(variable: str) -> str:
    """Return the unit the registry of series or of fields gives ``variable``."""
    if variable in TIME_SERIES_REGISTRY:
        return TIME_SERIES_REGISTRY[variable].units
    if variable in FIELD_REGISTRY:
        return FIELD_REGISTRY[variable].units
    pytest.fail(f"the series {variable!r} is in no registry")


def _assert_registered_with_unit(rows: pd.DataFrame) -> None:
    """Every simulated variable has a descriptor, and its rows carry the unit of it."""
    for variable, group in rows.groupby("variable"):
        expected = udunits_spelling(_registered_unit(str(variable)))
        assert set(group["unit"]) == {expected}, f"{variable}: {set(group['unit'])} != {expected}"


def _station_values(rows: pd.DataFrame, station: str, variable: str) -> pd.DataFrame:
    chosen = rows[(rows["station_id"] == station) & (rows["variable"] == variable)]
    assert not chosen.empty, f"no {variable} under {station}"
    return chosen.set_index("timestep").sort_index()


def _written_well_flows(project_toml: Path) -> list[float]:
    """Return the flow of each well of the project, in m3/s, as the file wrote it."""
    config = tomllib.loads(project_toml.read_text(encoding="utf-8"))
    wells = config["flow"]["sinks_sources"]["wells"]
    assert all(well["units"] == "m3/s" for well in wells.values())
    return [float(well["flux"]) for well in wells.values()]


def _assert_wells_pump_what_was_written(rows: pd.DataFrame, project_toml: Path) -> None:
    """The ``well_pumping`` of the catchment is the sum of the written flows, to 0.01 %.

    A well that MODFLOW 6 cuts in a nearly dry cell would show less, so a
    shortfall here means a well the project did not place well.
    """
    pumped = _station_values(rows, "catchment", "well_pumping")["value"].to_numpy()
    expected = np.full(pumped.shape, sum(_written_well_flows(project_toml)))
    assert pumped == pytest.approx(expected, rel=1e-4)


def test_a_lake_island_writes_its_series(
    tmp_path: Path, scenario_env: dict[str, str], scenario_cache: Path
) -> None:
    """The solved island stores registered series, and its storage term follows the volume.

    The well pumps what the project wrote, with the sign of the file. The
    storage term of the lake is a rate. Over a step, the rate times the
    length of the step is the change of volume, of the opposite sign: a lake
    that fills has a negative storage term, as the descriptor of
    ``lake_storage`` says.
    """
    binaries = tmp_path / "binaries"
    _write_binary_inputs(binaries)
    files = lake_island_files(
        three_months=True, well=True, deep_abacus=True, binary_dir=str(binaries)
    )
    scenario = Scenario(
        name="lake_island",
        covers="the series of a solved lake with a wall, a barrier and a well",
        files=files,
        argv=("run", "project.toml"),
        needs=MF6_FILES,
    )

    played = play(scenario, tmp_path / "play", scenario_env, scenario_cache)

    assert played.returncode == 0, played.log.read_text(encoding="utf-8")[-2000:]
    rows = _simulated_series(_run_folder(played))
    _assert_registered_with_unit(rows)

    lake_rows = rows[rows["station_id"] == LAKE_STATION]
    assert "lake_storage" in set(lake_rows["variable"])
    assert "storage" not in set(rows["variable"]), "a series named storage was written"
    assert "cutoff_wall_flow" in set(rows["variable"])
    assert "well_pumping" in set(rows["variable"])
    _assert_wells_pump_what_was_written(rows, played.root / "project.toml")

    volume = _station_values(rows, LAKE_STATION, "volume")
    storage = _station_values(rows, LAKE_STATION, "lake_storage")
    assert list(volume.index) == list(storage.index)
    seconds = volume["time"].diff().dt.total_seconds()
    change = volume["value"].diff()
    moved = [
        step
        for step in volume.index[1:]
        if abs(change[step]) > 1e-3 * volume["value"].shift(1)[step]
    ]
    assert moved, "the volume of the lake never moved, the storage term is not held"
    for step in moved:
        term = storage["value"][step] * seconds[step]
        assert term * change[step] < 0, (
            f"step {step}: storage {term} and volume change {change[step]}"
        )
        assert abs(term) == pytest.approx(abs(change[step]), rel=0.01), f"step {step}"


def test_a_valley_river_feeds_its_lake(
    tmp_path: Path, scenario_env: dict[str, str], scenario_cache: Path
) -> None:
    """The stream network of the valley flows into the lake, and both write registered series.

    The project reads the committed fixture in place. A run never writes there,
    which the last check holds.
    """
    before = sorted(path.name for path in CHEZE_DATA.iterdir())
    scenario = Scenario(
        name="cheze_valley",
        covers="stream and lake series of a solved valley with two wells",
        files=cheze_valley_files(str(CHEZE_DATA)),
        argv=("run", "project.toml"),
        needs=MF6_FILES,
    )

    played = play(scenario, tmp_path / "play", scenario_env, scenario_cache)

    assert played.returncode == 0, played.log.read_text(encoding="utf-8")[-2000:]
    rows = _simulated_series(_run_folder(played))
    _assert_registered_with_unit(rows)

    stations = set(rows["station_id"])
    reaches = {station for station in stations if station.startswith("net0:")}
    assert reaches, f"no stream reach station among {sorted(stations)}"
    assert "lake:res0" in stations
    assert "lake_storage" in set(rows[rows["station_id"] == "lake:res0"]["variable"])

    _assert_wells_pump_what_was_written(rows, played.root / "project.toml")

    assert sorted(path.name for path in CHEZE_DATA.iterdir()) == before
