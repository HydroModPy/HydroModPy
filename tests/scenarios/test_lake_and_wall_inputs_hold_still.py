def _prepare_inputs(root: Path) -> None:
    """Create test inputs in the project's inputs/ folder."""
    import geopandas as gpd
    import numpy as np
    import rasterio
    from rasterio.transform import from_origin
    from shapely.geometry import LineString

    inputs = root / "inputs"
    inputs.mkdir(parents=True, exist_ok=True)

    (inputs / "lake_polygon.geojson").write_text(json.dumps(_GEOMETRY, indent=1), encoding="utf-8")
    (inputs / "lake_abacus.csv").write_text(_ABACUS_CSV, encoding="utf-8")
    (inputs / "cutoff_wall.csv").write_text(_WALL_CSV, encoding="utf-8")

    rows, cols = 9, 11
    yy, xx = np.mgrid[0:rows, 0:cols]
    depth = np.clip(0.5 * (1.0 - ((yy - 4.0) / 4.0) ** 2 - ((xx - 5.0) / 5.0) ** 2), 0.05, None)
    bed = 10.0 - depth

    with rasterio.open(
        inputs / "lake_bathymetry.tif",
        "w",
        driver="GTiff",
        height=rows,
        width=cols,
        count=1,
        dtype="float64",
        crs="EPSG:2154",
        transform=from_origin(260.0, 340.0, 100.0 / cols, 80.0 / rows),
    ) as dst:
        dst.write(bed, 1)

    trace_ = LineString([(480.0, 200.0), (480.0, 420.0)])
    gpd.GeoDataFrame({"id": ["dam"]}, geometry=[trace_], crs="EPSG:2154").to_file(
        inputs / "barrier.gpkg", driver="GPKG"
    )

    (root / "project.toml").write_text(_PROJECT_TOML, encoding="utf-8")


def test_lake_and_wall_inputs_hold_still(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """Verify bit-for-bit equivalence of generated lak, hfb, and mesh outputs."""
    import hydromodpy.solver.base.runner as runner_module
    from hydromodpy.project.facade import Project

    _prepare_inputs(tmp_path)
    monkeypatch.chdir(tmp_path)

    orig_solve_one = runner_module.solve_one

    def _patched_solve_one(adapter, model, options, slot, upstream=(), **kwargs):
        slot = replace(slot, stop_before_solve=True)
        res = orig_solve_one(adapter, model, options, slot, upstream, **kwargs)
        if hasattr(res.solver_model, "sim"):
            res.solver_model.sim.write_simulation(silent=True)
        return res

    monkeypatch.setattr(runner_module, "solve_one", _patched_solve_one)

    proj = Project(tmp_path / "project.toml", no_display=True)
    try:
        proj.simulate(until_step="run_solver")
    finally:
        proj.close()

    solver_candidates = sorted((tmp_path / "runs").glob("*/.hmp/scratch/*")) + sorted(
        (tmp_path / "runs").glob("*/solver/*")
    )
    assert solver_candidates, "No solver directory generated"
    solver_dir = solver_candidates[0]

    digests: dict[str, str] = {}
    for suffix, key in (
        (".lak", "lak"),
        (".hfb", "hfb"),
        (".disv", "disv"),
    ):
        matches = sorted(solver_dir.glob(f"*{suffix}"))
        assert matches, f"Missing {suffix} file in {solver_dir}"
        digests[key] = _sha256_without_flopy_header(matches[0])

    mesh_cache = tmp_path / ".hmp" / "mesh_cache"
    assert mesh_cache.is_dir(), "No mesh cache found"
    npz_matches = sorted(mesh_cache.glob("*/mesh.npz"))
    assert npz_matches, "Missing mesh.npz"
    digests["mesh_npz"] = _sha256_of(npz_matches[0])

    json_matches = sorted(mesh_cache.glob("*/mesh.json"))
    assert json_matches, "Missing mesh.json"
    digests["mesh_json"] = _sha256_of(json_matches[0])

    for key, expected_digest in BASE_DIGESTS.items():
        actual = digests.get(key)
        assert actual == expected_digest, (
            f"Digest mismatch for {key}: {actual} != {expected_digest}"
        )
