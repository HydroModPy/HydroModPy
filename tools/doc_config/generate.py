def _scan_section_to_cases() -> dict[str, list[tuple[str, str]]]:
    """Map TOML section name to list of (slug, title) tuples that reference it."""
    out: dict[str, set[tuple[str, str]]] = defaultdict(set)
    if not GALLERY_VALIDATION_DIR.exists():
        return {k: sorted(v) for k, v in out.items()}
    for path in GALLERY_VALIDATION_DIR.glob("*_summary.json"):
        try:
            data = json.loads(path.read_text())
        except Exception:
            continue
        slug = data.get("slug") or path.stem.removesuffix("_summary")
        title = data.get("title", slug)
        seen_sections: set[str] = set()
        param_docs = data.get("parameter_docs", {})
        for bucket in ("reference_parameters", "common_setup"):
            for entry in param_docs.get(bucket, []) or []:
                field = entry.get("field", "")
                if "." in field:
                    seen_sections.add(field.split(".", 1)[0])
        for solver_overrides in (param_docs.get("solver_overrides") or {}).values():
            for entry in solver_overrides:
                field = entry.get("field", "")
                if "." in field:
                    seen_sections.add(field.split(".", 1)[0])
        for section in seen_sections:
            out[section].add((slug, title))
    return {k: sorted(v) for k, v in out.items()}


