_PROFILE_BADGE_CLASS = {
    Profile.USER: ("bdg-success", "user"),
    Profile.DEV: ("bdg-warning", "dev"),
    Profile.EXPERT: ("bdg-danger", "expert"),
}


def _field_profile(field: FieldInfo) -> Profile:
    return extract_profile(field)


def _field_stability(field: FieldInfo) -> str:
    extra = field.json_schema_extra
    if isinstance(extra, dict):
        value = extra.get("stability") or extra.get("hmp_stability")
        if isinstance(value, str):
            normalized = value.strip().lower()
            if normalized in {"stable", "experimental", "deprecated"}:
                return normalized
    return "stable"


def _class_source_link(model: type[BaseModel]) -> str | None:
    """Return a GitHub permalink to the class declaration line."""
    try:
        source_path = Path(inspect.getfile(model)).resolve()
    except (TypeError, OSError):
        return None
    try:
        relative = source_path.relative_to(REPO_ROOT)
    except ValueError:
        return None
    base = f"https://github.com/{GITHUB_REPO}/blob/{GITHUB_BRANCH}/{relative.as_posix()}"
    try:
        _lines, start = inspect.getsourcelines(model)
    except (OSError, TypeError):
        return base
    return f"{base}#L{start}"


def _field_source_link(model: type[BaseModel], field_name: str) -> str | None:
    """Return a GitHub permalink to the line where ``field_name`` is declared.

    Falls back to the class location if the field cannot be located.
    """
    try:
        source_path = Path(inspect.getfile(model)).resolve()
    except (TypeError, OSError):
        return None
    try:
        relative = source_path.relative_to(REPO_ROOT)
    except ValueError:
        return None
    base = f"https://github.com/{GITHUB_REPO}/blob/{GITHUB_BRANCH}/{relative.as_posix()}"
    try:
        lines, start = inspect.getsourcelines(model)
    except (OSError, TypeError):
        return base
    pattern = re.compile(rf"^\s*{re.escape(field_name)}\s*[:=]")
    for offset, line in enumerate(lines):
        if pattern.match(line):
            return f"{base}#L{start + offset}"
    return f"{base}#L{start}"


