_ANCHOR_INVALID = re.compile(r"[^a-z0-9-]+")


def _anchor_id(*parts: str) -> str:
    raw = "-".join(part.replace(".", "-").replace("_", "-") for part in parts if part)
    cleaned = _ANCHOR_INVALID.sub("-", raw.lower()).strip("-")
    return re.sub(r"-+", "-", cleaned)


def _toml_path(*parts: str) -> str:
    return ".".join(part for part in parts if part)


def _toml_usage(field: FieldInfo, full_path: str) -> str:
    """Return how ``full_path`` is meant to appear in a TOML file.

    - ``[[full_path]]`` for ``list[BaseModel]``
    - ``[full_path.<id>]`` for ``dict[str, ...]``
    - ``[full_path]`` for ``BaseModel``
    - ``full_path = ...`` for scalars
    """
    annotation = field.annotation
    inner_models = _get_inner_basemodels(annotation)
    annotation_str = _format_annotation(field).lower()
    if "list[" in annotation_str and inner_models:
        return f"[[{full_path}]]"
    if "dict[" in annotation_str:
        return f"[{full_path}.<id>]"
    if inner_models:
        return f"[{full_path}]"
    return f"{full_path} = ..."


def _render_field_block(
    field_name: str,
    field: FieldInfo,
    *,
    model: type[BaseModel],
    section_path: str,
    depth: int,
    indent: str,
    seen: set[int],
    anchor_namespace: str = "",
) -> list[str]:
    """Render one Pydantic field with a wrapper carrying anchor + level class."""
    type_str, badge = _field_badges(field)
    profile = _field_profile(field)
    stability = _field_stability(field)
    source_link = _field_source_link(model, field_name)

    inner_models = _get_inner_basemodels(field.annotation)
    discriminator = _find_discriminator(inner_models) if len(inner_models) > 1 else None
    annotation_str = _format_annotation(field).lower()
    dynamic_key = "<id>" if "dict[" in annotation_str else ""

    full_path = _toml_path(section_path, field_name)
    anchor = _anchor_id(anchor_namespace, full_path) if anchor_namespace else _anchor_id(full_path)
    level_class = _PROFILE_BADGE_CLASS[profile][1]

    if discriminator is not None:
        disc_name, disc_tags = discriminator
        choices = " | ".join(f'"{tag}"' for tag in disc_tags.values())
        type_badge = f":bdg-primary:`{disc_name} = {choices}`"
    else:
        type_badge = f":bdg-primary:`{type_str}`"

    toml_usage = _toml_usage(field, full_path)
    inner = indent + "   "
    lines: list[str] = [
        f"{indent}.. container:: hmp-field hmp-field-level-{level_class}",
        f"{indent}   :name: {anchor}",
        "",
        f"{inner}.. raw:: html",
        "",
        f'{inner}   <div class="hmp-field-header" data-toml-path="{html.escape(full_path, quote=True)}">',
        f'{inner}     <code class="hmp-field-name">{html.escape(field_name)}</code>',
        f'{inner}     <span class="hmp-field-arrow">in TOML:</span>',
        f'{inner}     <code class="hmp-field-toml">{html.escape(toml_usage)}</code>',
        f"{inner}   </div>",
        "",
    ]
    badge_parts = [type_badge, badge, _profile_badge(profile)]
    stability_part = _stability_badge(stability)
    if stability_part is not None:
        badge_parts.append(stability_part)
    if source_link is not None:
        badge_parts.append(f"`source <{source_link}>`__")
    lines.append(f"{inner}{' '.join(badge_parts)}")
    lines.append("")

    description_lines = _format_description(field.description or "", inner)
    if description_lines:
        lines.extend(description_lines)
        lines.append("")
    if discriminator is not None:
        disc_name, _ = discriminator
        lines.append(
            f"{inner}   Set ``{disc_name}`` in your TOML to choose one of the schemas below."
        )
        lines.append("")

    if depth < MAX_NESTED_DEPTH:
        for inner_model in inner_models:
            if id(inner_model) in seen:
                continue
            nested_seen = seen | {id(inner_model)}
            if discriminator is not None:
                disc_name, disc_tags = discriminator
                tag = disc_tags[inner_model]
                title = f'``{disc_name} = "{tag}"``  ({inner_model.__name__})'
                hidden_field = disc_name
                nested_path = _toml_path(full_path, tag, dynamic_key)
                child_namespace = anchor_namespace
            else:
                title = f"Fields of ``{inner_model.__name__}``"
                hidden_field = None
                nested_path = _toml_path(full_path, dynamic_key)
                if len(inner_models) > 1:
                    sub_namespace = inner_model.__name__.lower()
                    child_namespace = (
                        f"{anchor_namespace}-{sub_namespace}" if anchor_namespace else sub_namespace
                    )
                else:
                    child_namespace = anchor_namespace
            lines.extend(
                [
                    f"{inner}.. dropdown:: {title}",
                    f"{inner}   :icon: list-unordered",
                    f"{inner}   :animate: fade-in-slide-down",
                    "",
                    f"{inner}   .. rst-class:: hmp-config-fields hmp-config-fields-nested",
                    "",
                ]
            )
            sub_indent = inner + "   "
            for sub_name, sub_field in inner_model.model_fields.items():
                if getattr(sub_field, "exclude", False):
                    continue
                if hidden_field is not None and sub_name == hidden_field:
                    continue
                lines.extend(
                    _render_field_block(
                        sub_name,
                        sub_field,
                        model=inner_model,
                        section_path=nested_path,
                        depth=depth + 1,
                        indent=sub_indent,
                        seen=nested_seen,
                        anchor_namespace=child_namespace,
                    )
                )
            lines.append("")
    elif inner_models:
        lines.append(
            f"{inner}*Nested structure truncated at depth {MAX_NESTED_DEPTH}. "
            f"See :doc:`config_index` for the complete TOML path listing.*"
        )
        lines.append("")

    lines.append("")
    return lines


# ---------------------------------------------------------------------------
# TOML starter snippet (auto-derived from USER-profile defaults)
# ---------------------------------------------------------------------------


def _render_starter_snippet(section_name: str, model: type[BaseModel]) -> list[str]:
    """Return a minimal TOML starter for ``[section_name]`` (USER fields only).

    Top-level scalars first, then nested ``BaseModel`` and list[BaseModel]
    fields rendered as ``[parent.subfield]`` / ``[[parent.subfield]]``
    sub-tables so the user sees the full TOML shape, not just the leaves.
    """
    lines = [f"[{section_name}]"]
    nested_subtables: list[tuple[str, type[BaseModel]]] = []

    for field_name, field in model.model_fields.items():
        if getattr(field, "exclude", False):
            continue
        if _field_profile(field) is not Profile.USER:
            continue
        inner_models = _get_inner_basemodels(field.annotation)
        annotation_str = _format_annotation(field).lower()
        if "list[" in annotation_str and inner_models:
            nested_subtables.append((f"[[{section_name}.{field_name}]]", inner_models[0]))
            continue
        if "dict[" in annotation_str:
            lines.append(f"# [{section_name}.{field_name}.<id>]")
            continue
        if inner_models:
            nested_subtables.append((f"[{section_name}.{field_name}]", inner_models[0]))
            continue
        if field.is_required():
            lines.append(f"# {field_name} = {_toml_placeholder(field)}  # REQUIRED")
            continue
        if field.default_factory is not None:
            lines.append(f"# {field_name} = ...  # uses factory default")
            continue
        default = field.default
        if isinstance(default, str):
            lines.append(f'# {field_name} = "{default}"')
        elif isinstance(default, bool):
            lines.append(f"# {field_name} = {'true' if default else 'false'}")
        elif isinstance(default, Path):
            lines.append(f'# {field_name} = "{default.as_posix()}"')
        elif default is None:
            lines.append(f"# {field_name} = ...  # default = None")
        else:
            lines.append(f"# {field_name} = {default!r}")

    for header, sub_model in nested_subtables:
        lines.append("")
        lines.append(header)
        for sub_name, sub_field in sub_model.model_fields.items():
            if getattr(sub_field, "exclude", False):
                continue
            if _field_profile(sub_field) is not Profile.USER:
                continue
            if sub_field.is_required():
                lines.append(f"# {sub_name} = {_toml_placeholder(sub_field)}  # REQUIRED")
            elif sub_field.default_factory is not None:
                lines.append(f"# {sub_name} = ...  # factory default")
            else:
                default = sub_field.default
                if isinstance(default, str):
                    lines.append(f'# {sub_name} = "{default}"')
                elif isinstance(default, bool):
                    lines.append(f"# {sub_name} = {'true' if default else 'false'}")
                elif isinstance(default, Path):
                    lines.append(f'# {sub_name} = "{default.as_posix()}"')
                elif default is None:
                    lines.append(f"# {sub_name} = ...  # default = None")
                else:
                    lines.append(f"# {sub_name} = {default!r}")
    return lines


