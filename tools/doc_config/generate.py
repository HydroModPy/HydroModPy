def _unwrap(annotation: Any) -> Any:
    """Strip Annotated/Optional/Union wrappers and return the inner BaseModel."""
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        return annotation
    args = getattr(annotation, "__args__", ()) or ()
    for arg in args:
        if isinstance(arg, type) and issubclass(arg, BaseModel):
            return arg
    return annotation


def _format_default(field: FieldInfo) -> str:
    if field.is_required():
        return "required"
    if field.default_factory is not None:
        return "factory"
    default = field.default
    if isinstance(default, str):
        return f'"{default}"'
    if isinstance(default, Path):
        return f'"{default.as_posix()}"'
    return repr(default)


_TYPE_CLEAN_PATTERNS: list[tuple[re.Pattern[str], str]] = [
    (re.compile(r"<class '([^']+)'>"), r"\1"),
    (re.compile(r"\bpathlib\._local\."), ""),
    (re.compile(r"\bpathlib\."), ""),
    (re.compile(r"\btyping\."), ""),
    (re.compile(r"\bhydromodpy\."), ""),
    (re.compile(r"\bhmp\."), ""),
    (re.compile(r"\b(?:[\w]+\.)+(?=[A-Z]\w*\b)"), ""),
]


def _strip_annotated(text: str) -> str:
    """Replace ``Annotated[T, ...]`` with ``T`` (recursively) in a type string."""
    keyword = "Annotated["
    while True:
        idx = text.find(keyword)
        if idx == -1:
            return text
        start = idx + len(keyword)
        depth = 0
        first_comma = -1
        close = -1
        i = start
        while i < len(text):
            c = text[i]
            if c == "[":
                depth += 1
            elif c == "]":
                if depth == 0:
                    close = i
                    break
                depth -= 1
            elif c == "," and depth == 0 and first_comma == -1:
                first_comma = i
            i += 1
        if close == -1:
            return text
        first_arg_end = first_comma if first_comma != -1 else close
        first_arg = text[start:first_arg_end].strip()
        text = text[:idx] + first_arg + text[close + 1 :]


def _clean_type_str(text: str) -> str:
    text = _strip_annotated(text)
    for pattern, repl in _TYPE_CLEAN_PATTERNS:
        text = pattern.sub(repl, text)
    return text.strip()


def _format_annotation(field: FieldInfo) -> str:
    annotation = field.annotation
    if isinstance(annotation, type):
        return annotation.__name__
    return _clean_type_str(str(annotation))


def _section_title(name: str) -> str:
    return name.replace("_", " ").title()


