# Field badges and TOML placeholders
# ---------------------------------------------------------------------------


def _field_badges(field: FieldInfo) -> tuple[str, str]:
    type_str = _format_annotation(field)
    default = _format_default(field)
    if default == "required":
        meta = ":bdg-danger:`required`"
    elif default == "factory":
        meta = ":bdg-info:`factory`"
    else:
        meta = f":bdg-secondary:`default = {default}`"
    return type_str, meta


def _stability_badge(stability: str) -> str | None:
    if stability == "stable":
        return None
    if stability == "experimental":
        return ":bdg-warning:`experimental`"
    if stability == "deprecated":
        return ":bdg-danger:`deprecated`"
    return None


def _profile_badge(profile: Profile) -> str:
    badge_class, label = _PROFILE_BADGE_CLASS[profile]
    return f":{badge_class}:`{label}`"


def _toml_placeholder(field: FieldInfo) -> str:
    """Return one TOML-valid placeholder for ``field``.

    Used by Couche 4 to keep copy-paste blocks parseable. Required and
    factory fields are emitted as commented-out lines.
    """
    annotation_str = _format_annotation(field).lower()
    if "bool" in annotation_str:
        return "false"
    if "int" in annotation_str:
        return "0"
    if "float" in annotation_str:
        return "0.0"
    if "list" in annotation_str:
        return "[]"
    if "dict" in annotation_str:
        return "{}"
    return '""'


