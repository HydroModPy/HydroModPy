"""Generate the configuration reference RST tree for HydroModPy.

Outputs five layers under ``docs/source/user_guide/config_reference/``:

- ``index.rst`` (Couche 1): overview page with a grid card per top-level
  section.
- ``<section>.rst`` (Couche 2): one page per top-level section listing
  its direct fields and their type, default, description, with a TOML
  starter snippet, GitHub source links, profile filtering and stability
  badges.
- ``schema_explorer.rst`` (Couche 3): interactive Stoplight Elements view
  of the JSON Schema exported from ``HydroModPyConfig``. The schema JSON
  is also written to ``docs/source/_static/hydromodpy-schema.json`` for
  external tools.
- ``complete_toml.rst`` (Couche 4): one page with the complete annotated
  TOML reference grouped by section, producing valid copy-pasteable TOML
  (required and factory fields are commented out with a placeholder).
- ``config_index.rst`` (Couche 5): flat global index of every TOML path
  with type, profile, page link and GitHub source link. Cible Ctrl+F.
"""

