# Description formatting (paragraphs + bullets)
# ---------------------------------------------------------------------------


_BULLET_RE = re.compile(r"^\s*[-*+]\s+")


def _format_description(text: str, indent: str) -> list[str]:
    """Render a Pydantic description preserving paragraphs and bullets.

    Paragraphs are split on blank lines. Within a paragraph, single newlines
    collapse to spaces unless any line starts with a bullet marker.
    """
    text = (text or "").strip()
    if not text:
        return []
    paragraphs = re.split(r"\n[ \t]*\n", text)
    out: list[str] = []
    for index, paragraph in enumerate(paragraphs):
        if index > 0:
            out.append("")
        raw_lines = paragraph.split("\n")
        if any(_BULLET_RE.match(line) for line in raw_lines):
            for line in raw_lines:
                out.append(f"{indent}   {line.rstrip()}" if line.strip() else "")
        else:
            collapsed = " ".join(line.strip() for line in raw_lines if line.strip())
            out.append(f"{indent}   {collapsed}")
    return out


# ---------------------------------------------------------------------------
# Discriminated union detection
# ---------------------------------------------------------------------------


def _get_inner_basemodels(annotation: Any) -> list[type[BaseModel]]:
    """Return every BaseModel reachable inside Optional/Union/list, in order."""
    found: list[type[BaseModel]] = []
    seen_ids: set[int] = set()

    def visit(node: Any) -> None:
        if isinstance(node, type) and issubclass(node, BaseModel):
            if id(node) not in seen_ids:
                seen_ids.add(id(node))
                found.append(node)
            return
        for arg in getattr(node, "__args__", ()) or ():
            visit(arg)

    visit(annotation)
    return found


def _find_discriminator(
    models: list[type[BaseModel]],
) -> tuple[str, dict[type[BaseModel], str]] | None:
    """Detect a tagged-union discriminator across ``models``."""
    if len(models) < 2:
        return None
    common = set(models[0].model_fields.keys())
    for m in models[1:]:
        common &= set(m.model_fields.keys())
    for field_name in sorted(common):
        tags: dict[type[BaseModel], str] = {}
        ok = True
        for model in models:
            f = model.model_fields[field_name]
            if f.is_required() or f.default_factory is not None:
                ok = False
                break
            value = f.default
            if not isinstance(value, str):
                ok = False
                break
            tags[model] = value
        if ok and len(set(tags.values())) == len(models):
            return field_name, tags
    return None


