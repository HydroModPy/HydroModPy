def _render_couche1(top_fields: dict[str, FieldInfo]) -> str:
    lines = [
        GENERATED_HEADER,
        "Configuration overview",
        "======================",
        "",
        "Card-based map of every TOML section validated by ``HydroModPyConfig``.",
        "Click a card to open the section detail page.",
        "",
        "**Companion pages**",
        "",
        "- :doc:`config_index` -- flat global index, Ctrl+F friendly",
        "- :doc:`complete_toml` -- full annotated TOML reference",
        "- :doc:`schema_explorer` -- interactive JSON Schema viewer",
        "- :doc:`recipes` -- task-oriented cookbook",
        "- :doc:`validate` -- pre-flight your project.toml in the browser",
        "",
        "Quick search across every TOML path",
        "-----------------------------------",
        "",
        ".. raw:: html",
        "",
        '   <div class="hmp-config-search">',
        '     <input type="search" id="hmp-config-search-input" '
        'placeholder="Search any field, section, or TOML path..."'
        ' autocomplete="off" />',
        '     <div id="hmp-config-search-results" class="hmp-config-search-results"></div>',
        "   </div>",
        "",
        "Sections",
        "--------",
        "",
        ".. grid:: 1 1 2 3",
        "   :gutter: 2 2 3 3",
        "",
    ]
    for name, field in top_fields.items():
        model = _unwrap(field.annotation)
        if not (isinstance(model, type) and issubclass(model, BaseModel)):
            continue
        description = (field.description or "").replace("\n", " ").strip()
        lines.extend(
            [
                "   .. grid-item-card::",
                f"      :link: {name}",
                "      :link-type: doc",
                "      :class-card: sd-shadow-sm sd-rounded-3 sd-p-3",
                "",
                f"      **[{name}]**",
                "      ^^^",
                f"      {description or _section_title(name)}",
                "",
            ]
        )
    lines.extend(
        [
            ".. toctree::",
            "   :hidden:",
            "",
            "   config_index",
            "   complete_toml",
            "   schema_explorer",
            "   recipes",
            "   validate",
        ]
    )
    for name, field in top_fields.items():
        model = _unwrap(field.annotation)
        if isinstance(model, type) and issubclass(model, BaseModel):
            lines.append(f"   {name}")
    lines.append("")
    return "\n".join(lines)


