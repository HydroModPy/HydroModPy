# Couche 4: complete TOML reference (now valid TOML)
# ---------------------------------------------------------------------------


def _render_couche4(top_fields: dict[str, FieldInfo]) -> str:
    lines = [
        GENERATED_HEADER,
        "Complete annotated TOML reference",
        "=================================",
        "",
        "Every TOML section with its direct fields, defaults and types.",
        "Sub-models are linked back to their per-section page.",
        "",
        ".. tip::",
        "   The blocks below produce **valid TOML** when copy-pasted.",
        "   Required and factory fields are commented out: uncomment and",
        "   replace the placeholder before running the project.",
        "",
    ]
    for name, field in top_fields.items():
        model = _unwrap(field.annotation)
        if not (isinstance(model, type) and issubclass(model, BaseModel)):
            continue
        lines.append(f".. dropdown:: ``[{name}]`` ({model.__name__})")
        lines.append("   :icon: gear")
        lines.append("")
        lines.append(f"   See :doc:`{name}` for the full description.")
        lines.append("")
        lines.append("   .. code-block:: toml")
        lines.append("")
        lines.append(f"      [{name}]")
        for field_name, sub_field in model.model_fields.items():
            if getattr(sub_field, "exclude", False):
                continue
            description = (sub_field.description or "no description").replace("\n", " ").strip()
            lines.append(f"      # {description}")
            if sub_field.is_required():
                placeholder = _toml_placeholder(sub_field)
                lines.append(f"      # {field_name} = {placeholder}  # REQUIRED")
            elif sub_field.default_factory is not None:
                lines.append(f"      # {field_name} = ...  # uses factory default")
            else:
                default = sub_field.default
                if isinstance(default, str):
                    lines.append(f'      {field_name} = "{default}"')
                elif isinstance(default, bool):
                    lines.append(f"      {field_name} = {'true' if default else 'false'}")
                elif isinstance(default, Path):
                    lines.append(f'      {field_name} = "{default.as_posix()}"')
                elif default is None:
                    lines.append(f"      # {field_name} = ...  # default = None")
                else:
                    lines.append(f"      {field_name} = {default!r}")
        lines.append("")
    return "\n".join(lines)


