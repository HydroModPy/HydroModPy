def export_schema(output_path: Path | None = None) -> Path:
    """Write the canonical JSON Schema to ``_static/hydromodpy-schema.json``."""
    target = (output_path or SCHEMA_OUTPUT).resolve()
    target.parent.mkdir(parents=True, exist_ok=True)
    schema = HydroModPyConfig.model_json_schema()
    target.write_text(json.dumps(schema, indent=2, sort_keys=False) + "\n")
    return target


def export_search_index(top_fields: dict[str, FieldInfo], output_path: Path | None = None) -> Path:
    """Write a flat JSON index used by the in-page Ctrl+F search widget."""
    entries: list[dict[str, str]] = []
    for name, field in top_fields.items():
        model = _unwrap(field.annotation)
        if not (isinstance(model, type) and issubclass(model, BaseModel)):
            continue
        for full_path, type_str, profile, stability, source in _walk_field_paths(model, name):
            anchor = _anchor_id(full_path)
            field_name = full_path.rsplit(".", 1)[-1]
            field_info = _field_info_for_path(model, full_path[len(name) + 1 :])
            description = ""
            if field_info is not None and field_info.description:
                description = field_info.description.replace("\n", " ").strip()[:240]
            entries.append(
                {
                    "path": full_path,
                    "name": field_name,
                    "type": type_str,
                    "profile": profile,
                    "stability": stability,
                    "section": name,
                    "anchor": anchor,
                    "page": f"{name}.html",
                    "source": source or "",
                    "description": description,
                }
            )
    target = (output_path or SEARCH_INDEX_OUTPUT).resolve()
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(entries, indent=2, sort_keys=False) + "\n")
    return target


def _field_info_for_path(model: type[BaseModel], dotted: str) -> FieldInfo | None:
    """Drill into ``model`` along ``dotted`` (skipping unknown segments)."""
    if not dotted:
        return None
    current_model: type[BaseModel] | None = model
    info: FieldInfo | None = None
    for segment in dotted.split("."):
        if current_model is None:
            return None
        info = current_model.model_fields.get(segment)
        if info is None:
            return None
        inner = _get_inner_basemodels(info.annotation)
        current_model = inner[0] if inner else None
    return info


