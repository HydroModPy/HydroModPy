def _try_render_er_diagram(model: type, output_path: Path) -> Path | None:
    """Render an ER SVG for ``model``.

    Returns the path on success, or the previously rendered path if it
    already exists on disk and the new render fails (graphviz ``dot``
    missing, etc.). Returns ``None`` only when no SVG can be exposed.
    """
    try:
        import erdantic
    except ImportError:
        return output_path if output_path.exists() else None
    try:
        diagram = erdantic.create(model)
        output_path.parent.mkdir(parents=True, exist_ok=True)
        diagram.draw(out=str(output_path))
        return output_path
    except Exception:
        return output_path if output_path.exists() else None


