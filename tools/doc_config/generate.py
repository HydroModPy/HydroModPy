# Couche 5: flat global index
# ---------------------------------------------------------------------------


def _walk_field_paths(
    model: type[BaseModel],
    section_path: str,
    *,
    depth: int = 0,
    seen: set[int] | None = None,
) -> list[tuple[str, str, str, str | None, str | None]]:
    """Return tuples (toml_path, type, profile, stability, source_url)."""
    if seen is None:
        seen = {id(model)}
    out: list[tuple[str, str, str, str | None, str | None]] = []
    for field_name, field in model.model_fields.items():
        if getattr(field, "exclude", False):
            continue
        full_path = _toml_path(section_path, field_name)
        type_str = _format_annotation(field)
        profile = _field_profile(field).name.lower()
        stability = _field_stability(field)
        source = _field_source_link(model, field_name)
        out.append((full_path, type_str, profile, stability, source))
        if depth < MAX_NESTED_DEPTH:
            inner_models = _get_inner_basemodels(field.annotation)
            discriminator = _find_discriminator(inner_models) if len(inner_models) > 1 else None
            annotation_str = _format_annotation(field).lower()
            dynamic_key = "<id>" if "dict[" in annotation_str else ""
            for inner in inner_models:
                if id(inner) in seen:
                    continue
                if discriminator is not None:
                    disc_name, disc_tags = discriminator
                    nested_path = _toml_path(full_path, disc_tags[inner], dynamic_key)
                else:
                    nested_path = _toml_path(full_path, dynamic_key)
                out.extend(
                    _walk_field_paths(
                        inner,
                        nested_path,
                        depth=depth + 1,
                        seen=seen | {id(inner)},
                    )
                )
    return out


def _render_couche5(top_fields: dict[str, FieldInfo]) -> str:
    lines = [
        GENERATED_HEADER,
        "Configuration index",
        "===================",
        "",
        "Flat list of every TOML path validated by ``HydroModPyConfig``.",
        "Use Ctrl+F to jump to a specific path. Each row links back to the",
        "per-section page (anchor) and to the source declaration on GitHub.",
        "",
        ".. list-table::",
        "   :header-rows: 1",
        "   :widths: 35 25 10 10 10 10",
        "   :class: hmp-config-index",
        "",
        "   * - TOML path",
        "     - Type",
        "     - Profile",
        "     - Stability",
        "     - Page",
        "     - Source",
    ]
    for name, field in top_fields.items():
        model = _unwrap(field.annotation)
        if not (isinstance(model, type) and issubclass(model, BaseModel)):
            continue
        for full_path, type_str, profile, stability, source in _walk_field_paths(model, name):
            anchor = _anchor_id(full_path)
            page_link = f"`{name} <{name}.html#{anchor}>`__"
            source_cell = f"`link <{source}>`__" if source else "-"
            stability_cell = stability if stability != "stable" else "-"
            lines.extend(
                [
                    f"   * - ``{full_path}``",
                    f"     - ``{type_str}``",
                    f"     - {profile}",
                    f"     - {stability_cell}",
                    f"     - {page_link}",
                    f"     - {source_cell}",
                ]
            )
    lines.append("")
    return "\n".join(lines)


