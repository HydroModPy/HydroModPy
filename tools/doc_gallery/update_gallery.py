def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(65536), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _missing_repo_paths(paths: tuple[str, ...] | list[str]) -> list[str]:
    missing: list[str] = []
    seen: set[str] = set()
    for relative_path in paths:
        normalized = str(relative_path).strip()
        if normalized == "" or normalized in seen:
            continue
        seen.add(normalized)
        if not _repo_path(normalized).exists():
            missing.append(normalized)
    return missing


def _json_ready(value: Any) -> Any:
    if isinstance(value, Path):
        return _repo_relative(value)
    if isinstance(value, np.generic):
        return value.item()
    if isinstance(value, np.ndarray):
        return value.tolist()
    if isinstance(value, dict):
        return {str(key): _json_ready(item) for key, item in value.items()}
    if isinstance(value, (list, tuple, set)):
        return [_json_ready(item) for item in value]
    if isinstance(value, (str, int, float, bool)) or value is None:
        return value
    return str(value)


def _build_source_hashes(source_paths: tuple[str, ...]) -> dict[str, str]:
    hashes: dict[str, str] = {}
    for relative_path in source_paths:
        source_path = _repo_path(relative_path)
        if source_path.exists():
            hashes[relative_path] = _sha256(source_path)
        else:
            hashes[relative_path] = MISSING_SOURCE_HASH
    return hashes


