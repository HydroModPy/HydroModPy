def _append_figure(
    lines: list[str],
    image: dict[str, Any],
    *,
    indent: str = "",
    width: str = "100%",
) -> None:
    lines.extend(
        [
            f"{indent}.. figure:: {image['doc_path']}",
            f"{indent}   :alt: {image['alt_text']}",
            f"{indent}   :width: {width}",
            "",
            f"{indent}   {image['caption']}",
            "",
        ]
    )


def _append_mesh_tab_images(
    lines: list[str],
    images: list[dict[str, Any]],
    *,
    indent: str = "",
) -> None:
    if not images:
        return
    _append_figure(lines, images[0], indent=indent, width="85%")
    if len(images) > 1:
        _append_figure(lines, images[1], indent=indent, width="35%")


def _render_validation_solver_block(run: dict[str, Any], *, indent: str = "") -> list[str]:
    lines: list[str] = []
    image = run.get("image")
    if image:
        _append_figure(lines, image, indent=indent)

    if run.get("metric_lines"):
        lines.append(f"{indent}**Metrics**")
        for metric_line in run["metric_lines"]:
            lines.append(f"{indent}- {metric_line}")
        lines.append("")

    details: list[str] = []
    if run.get("config_path"):
        details.append(f"Config file: ``{run['config_path']}``")
    if run.get("tolerance_path"):
        details.append(f"Tolerances: ``{run['tolerance_path']}``")
    if run.get("expected_output"):
        details.append(str(run["expected_output"]))
    for item in details:
        lines.append(f"{indent}- {item}")
    if details:
        lines.append("")

    lines.extend(
        [
            f"{indent}.. code-block:: bash",
            "",
            f"{indent}   {run['command']}",
            "",
        ]
    )
    return lines


def _build_case_page(case: dict[str, Any]) -> str:
    title = str(case["title"])
    lines = [
        AUTO_GENERATED_COMMENT,
        "",
        title,
        "=" * len(title),
        "",
        *_render_note_block(),
        str(case["summary"]),
        "",
    ]
    solver_runs = list(case.get("solver_runs", []))
    if not solver_runs:
        for image in case["images"]:
            _append_figure(lines, image)

    if case["case_setup"]:
        lines.extend(
            [
                "Case Setup",
                "----------",
                "",
            ]
        )
        for bullet in case["case_setup"]:
            lines.append(f"- {bullet}")
        lines.append("")

    lines.extend(
        [
            "What It Shows",
            "-------------",
            "",
        ]
    )
    for bullet in case["what_it_shows"]:
        lines.append(f"- {bullet}")
    lines.append("")

    if case["metrics"]:
        lines.extend(
            [
                "Key Metrics",
                "-----------",
                "",
            ]
        )
        for metric in case["metrics"]:
            lines.append(f"- {metric['label']}: {metric['display']}")
        lines.append("")

    if case["reference_highlights"] or case["equations_rst"]:
        lines.extend(
            [
                "Analytical Reference",
                "--------------------",
                "",
            ]
        )
        for bullet in case["reference_highlights"]:
            lines.append(f"- {bullet}")
        if case["reference_highlights"] and case["equations_rst"]:
            lines.append("")
        for equation in case["equations_rst"]:
            lines.extend(
                [
                    ".. math::",
                    "",
                    f"   {equation}",
                    "",
                ]
            )
        if lines[-1] != "":
            lines.append("")

    if solver_runs:
        metadata = dict(case.get("metadata", {}))
        default_solver = metadata.get("default_solver")
        solver_display_names = [
            str(run.get("solver_display_name", run.get("solver", "")))
            for run in solver_runs
        ]
        lines.extend(
            [
                "Solver Coverage",
                "---------------",
                "",
            ]
        )
        if default_solver:
            default_label = next(
                (
                    run.get("solver_display_name", run.get("solver", ""))
                    for run in solver_runs
                    if run.get("solver") == default_solver
                ),
                default_solver,
            )
            lines.append(f"- Default solver: {default_label}")
        lines.append(f"- Available variants: {', '.join(solver_display_names)}")
        lines.append("")

        if len(solver_runs) > 1:
            lines.extend(
                [
                    ".. tab-set::",
                    "",
                ]
            )
            for run in solver_runs:
                lines.extend(
                    [
                        f"   .. tab-item:: {run['solver_display_name']}",
                        "",
                    ]
                )
                lines.extend(_render_validation_solver_block(run, indent="      "))
        else:
            lines.extend(_render_validation_solver_block(solver_runs[0]))

    lines.extend(
        [
            "Reproduce",
            "---------",
            "",
            "Run the underlying example or validation case with:",
            "",
            ".. code-block:: bash",
            "",
            f"   {case['reproduction_command']}",
            "",
            "Refresh the committed gallery artifacts with:",
            "",
            ".. code-block:: bash",
            "",
            f"   {case['gallery_update_command']}",
            "",
            "Source Pointers",
            "---------------",
            "",
        ]
    )
    for source_path in case["source_paths"]:
        lines.append(f"- ``{source_path}``")
    lines.append("")

    lines.extend(
        [
            "Artifacts",
            "---------",
            "",
        ]
    )
    for image_path in case["artifacts"]["image_repo_paths"]:
        lines.append(f"- ``{image_path}``")
    lines.append(
        "- ``{}`` stores the displayed metrics plus source hashes used by "
        "``python -m tools.doc_gallery --check``.".format(
            case["artifacts"]["summary_json_repo_path"]
        )
    )
    lines.append("")
    return "\n".join(lines)


def _collect_generated_files(source_root: Path) -> dict[str, Path]:
    collected: dict[str, Path] = {}
    for relative_dir in (
        Path("capability_gallery"),
        Path("_static") / "capability_gallery",
    ):
        target_dir = source_root / relative_dir
        if not target_dir.exists():
            continue
        for path in sorted(target_dir.rglob("*")):
            if path.is_file():
                collected[path.relative_to(source_root).as_posix()] = path
    return collected


def _compare_generated_trees(*, expected_source_root: Path, committed_source_root: Path) -> list[str]:
    expected_files = _collect_generated_files(expected_source_root)
    committed_files = _collect_generated_files(committed_source_root)
    issues: list[str] = []

    for relative_path in sorted(set(expected_files) - set(committed_files)):
        issues.append(f"Missing generated file: {relative_path}")
    for relative_path in sorted(set(committed_files) - set(expected_files)):
        issues.append(f"Unexpected generated file: {relative_path}")

    for relative_path in sorted(set(expected_files) & set(committed_files)):
        suffix = Path(relative_path).suffix.lower()
        if suffix not in TEXTUAL_SUFFIXES:
            continue
        if expected_files[relative_path].read_bytes() != committed_files[relative_path].read_bytes():
            issues.append(f"Stale generated file: {relative_path}")

    return issues


def _load_validation_batch_reports() -> list[dict[str, Any]]:
    reports: list[dict[str, Any]] = []
    if not VALIDATION_REPORT_DIR.exists():
        return reports

    for path in sorted(VALIDATION_REPORT_DIR.glob("*.json")):
        try:
            payload = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            continue
        if str(payload.get("schema_version", "")).strip() != "validation_batch_report_v1":
            continue
        payload["_report_repo_path"] = _repo_relative(path)
        reports.append(payload)

    solver_rank = {solver: index for index, solver in enumerate(VALIDATION_SOLVER_ORDER)}
    return sorted(
        reports,
        key=lambda payload: (
            solver_rank.get(str(payload.get("solver", "")).strip().lower(), 999),
            str(payload.get("_report_repo_path", "")),
        ),
    )


def generate_gallery(*, source_root: Path) -> None:
    """Generate the full gallery under one docs source tree."""

    _reset_generated_dirs(source_root)
    specs = build_gallery_specs()
    case_summaries = [_generate_case(spec, source_root) for spec in specs]
    summaries_by_category: dict[str, list[dict[str, Any]]] = {}
    for category_slug in CATEGORY_SPECS:
        summaries_by_category[category_slug] = [
            summary for summary in case_summaries if summary["category"] == category_slug
        ]

    docs_dir = source_root / "capability_gallery"
    static_dir = source_root / "_static" / "capability_gallery"
    case_dir = docs_dir / "cases"
    case_dir.mkdir(parents=True, exist_ok=True)

    for case in case_summaries:
        summary_path = static_dir / str(case["category"]) / f"{case['slug']}_summary.json"
        _write_json(summary_path, case)
        _write_text(case_dir / f"{case['slug']}.rst", _build_case_page(case))

    _write_text(docs_dir / "index.rst", _build_index_page(summaries_by_category))
    for category_slug, cases in summaries_by_category.items():
        if cases:
            _write_text(docs_dir / f"{category_slug}.rst", _build_category_page(category_slug, cases))


def main(argv: list[str] | None = None) -> int:
    """Entry point for ``python -m tools.doc_gallery``."""

    args = build_parser().parse_args(argv)
    if args.check:
        with tempfile.TemporaryDirectory(prefix="hydromodpy_doc_gallery_") as temp_dir:
            temp_source_root = Path(temp_dir) / "source"
            temp_source_root.mkdir(parents=True, exist_ok=True)
            generate_gallery(source_root=temp_source_root)
            issues = _compare_generated_trees(
                expected_source_root=temp_source_root,
                committed_source_root=DOCS_SOURCE_DIR,
            )
            if issues:
                print("Capability gallery is out of date. Regenerate it with:")
                print("  python -m tools.doc_gallery")
                for issue in issues:
                    print(f"- {issue}")
                return 1
        print("Capability gallery is in sync.")
        return 0

    generate_gallery(source_root=DOCS_SOURCE_DIR)
    print("Capability gallery refreshed under docs/readthedocs/source/.")
    return 0


