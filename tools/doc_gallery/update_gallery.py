def _render_mesh_coverage_matrix(cases: list[dict[str, Any]]) -> list[str]:
    """Render one compact scale/variant coverage matrix for versioned mesh cases."""

    coverage: dict[tuple[str, str], list[str]] = {}
    for case in cases:
        metadata = dict(case.get("metadata", {}))
        scale = str(metadata.get("scale", "")).strip()
        variant = str(metadata.get("variant", "")).strip()
        outlet_id = str(metadata.get("outlet_id", "")).strip()
        if scale == "" or variant == "":
            continue
        coverage.setdefault((scale, variant), [])
        if outlet_id:
            coverage[(scale, variant)].append(outlet_id)

    lines = [
        "Coverage Matrix",
        "---------------",
        "",
        ".. list-table::",
        "   :header-rows: 1",
        "",
        "   * - Scale",
    ]
    for variant in MESH_GALLERY_VARIANT_SPECS.values():
        lines.append(f"     - {variant['label']}")

    for scale in MESH_GALLERY_SCALE_ORDER:
        lines.append(f"   * - {mesh_scale_label(scale)}")
        for variant in MESH_GALLERY_VARIANT_SPECS:
            outlet_ids = coverage.get((scale, variant), [])
            if outlet_ids:
                outlet_suffix = ", ".join(f"outlet {item}" for item in sorted(outlet_ids))
                cell_value = f"Versioned ({outlet_suffix})"
            else:
                cell_value = "Missing"
            lines.append(f"     - {cell_value}")
    lines.append("")
    return lines


def _render_mesh_family_matrix(cases: list[dict[str, Any]]) -> list[str]:
    """Render one compact family/outlet matrix when repeated mesh families are declared."""

    families: dict[str, dict[str, Any]] = {}
    for case in cases:
        metadata = dict(case.get("metadata", {}))
        family_key = str(metadata.get("case_family_key", "")).strip()
        family_label = str(metadata.get("case_family_label", "")).strip()
        if family_key == "" or family_label == "":
            continue
        entry = families.setdefault(
            family_key,
            {
                "label": family_label,
                "order": int(metadata.get("case_family_order", 999)),
                "scale_label": str(metadata.get("scale_label", metadata.get("scale", ""))).strip(),
                "variant_label": str(metadata.get("variant_label", metadata.get("variant", ""))).strip(),
                "outlet_ids": [],
            },
        )
        outlet_id = str(metadata.get("outlet_id", "")).strip()
        if outlet_id != "":
            entry["outlet_ids"].append(outlet_id)

    if not families:
        return []

    lines = [
        "Family Coverage",
        "---------------",
        "",
        ".. list-table::",
        "   :header-rows: 1",
        "",
        "   * - Case family",
        "     - Scale",
        "     - Variant",
        "     - Imported outlets",
    ]
    for family in sorted(
        families.values(),
        key=lambda item: (int(item["order"]), str(item["label"])),
    ):
        ordered_outlets = sorted(
            set(str(item) for item in family["outlet_ids"]),
            key=lambda item: int(item) if str(item).isdigit() else str(item),
        )
        lines.extend(
            [
                f"   * - {family['label']}",
                f"     - {family['scale_label']}",
                f"     - {family['variant_label']}",
                f"     - {', '.join(f'outlet {item}' for item in ordered_outlets)}",
            ]
        )
    lines.append("")
    return lines


