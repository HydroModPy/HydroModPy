def _append_custom_sections(lines: list[str], custom_sections: list[dict[str, Any]]) -> None:
    for section in custom_sections:
        title = str(section.get("title", "")).strip()
        if title:
            lines.extend([title, "-" * len(title), ""])
        kind = str(section.get("kind", "paragraphs")).strip().lower()
        if kind == "paragraphs":
            for paragraph in section.get("paragraphs", []):
                text = str(paragraph).strip()
                if not text:
                    continue
                lines.extend([text, ""])
            continue
        if kind == "bullets":
            for bullet in section.get("items", []):
                text = str(bullet).strip()
                if text:
                    lines.append(f"- {text}")
            lines.append("")
            continue
        if kind == "list_table":
            headers = [
                str(item).strip() for item in section.get("headers", []) if str(item).strip()
            ]
            rows = [list(row) for row in section.get("rows", [])]
            if headers and rows:
                widths = section.get("widths", [])
                lines.append(".. list-table::")
                lines.append("   :header-rows: 1")
                if widths:
                    rendered_widths = " ".join(str(item) for item in widths)
                    lines.append(f"   :widths: {rendered_widths}")
                lines.append("")
                lines.append("   * - " + headers[0])
                for header in headers[1:]:
                    lines.append(f"     - {header}")
                for row in rows:
                    rendered = [str(item) for item in row]
                    if not rendered:
                        continue
                    lines.append(f"   * - {rendered[0]}")
                    for cell in rendered[1:]:
                        lines.append(f"     - {cell}")
                lines.append("")
            continue
        raise ValueError(f"Unsupported custom section kind: {kind}")


