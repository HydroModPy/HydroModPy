def _add_horizontal_colorbar(fig, mappable, *, axes, label: str):
    bbox = axes[0].get_position()
    right = axes[-1].get_position().x1
    bottom = min(ax.get_position().y0 for ax in axes) - 0.045
    height = 0.015
    cbar_ax = fig.add_axes([bbox.x0, max(0.02, bottom), right - bbox.x0, height])
    cbar = fig.colorbar(mappable, cax=cbar_ax, orientation="horizontal")
    cbar.set_label(label)
    return cbar


def _load_committed_simulation_comparison_payload(
    comparison_root: Path,
) -> tuple[dict[str, Any], dict[str, Any], list[dict[str, Any]]] | None:
    """Reuse committed simulation-comparison artifacts when they already exist."""

    manifest_path = comparison_root / "comparison_manifest.json"
    metrics_path = comparison_root / "comparison_metrics.json"
    observables_path = comparison_root / "observables.csv"
    if not (manifest_path.exists() and metrics_path.exists() and observables_path.exists()):
        return None

    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    metrics_payload = json.loads(metrics_path.read_text(encoding="utf-8"))
    with observables_path.open("r", encoding="utf-8", newline="") as handle:
        all_rows = list(csv.DictReader(handle))
    return manifest, metrics_payload, all_rows


def _build_simulation_comparison_payload(
    config_path: Path,
) -> tuple[dict[str, Any], dict[str, Any], list[dict[str, Any]]]:
    from hydromodpy.analysis.comparison.config import ComparisonConfig
    from hydromodpy.analysis.comparison.metric_diff import build_comparison_metrics
    from hydromodpy.analysis.comparison.runtime import (
        compact_run_metrics,
        read_json_file,
        read_simulation_run_metadata,
    )
    from hydromodpy.analysis.comparison.runtime_observables import (
        extract_observable_rows,
    )
    from hydromodpy.core.toml_io.loader import load_toml_with_base_config

    raw_toml = load_toml_with_base_config(config_path)
    cfg = ComparisonConfig.from_toml(raw_toml, config_path=config_path)
    section = cfg.comparison
    committed_payload = _load_committed_simulation_comparison_payload(cfg.comparison_root)
    if committed_payload is not None:
        return committed_payload

    committed_simulation_rows: dict[str, dict[str, Any]] = {}
    committed_manifest_path = cfg.comparison_root / "comparison_manifest.json"
    if section.run_simulations and not committed_manifest_path.exists():
        raise ValueError(
            "Capability-gallery simulation comparison cases with run_simulations=true "
            "must reuse one committed comparison_manifest.json."
        )
    if committed_manifest_path.exists():
        committed_manifest = read_json_file(committed_manifest_path)
        for row in list(committed_manifest.get("simulations", [])):
            if not isinstance(row, dict):
                continue
            simulation_id = str(row.get("id", "")).strip()
            if simulation_id != "":
                committed_simulation_rows[simulation_id] = row

    all_rows: list[dict[str, Any]] = []
    simulation_summaries: list[dict[str, Any]] = []
    for simulation in section.simulation:
        if not simulation.enabled:
            simulation_summaries.append(
                {
                    "id": simulation.id,
                    "label": simulation.label or simulation.id,
                    "status": "skipped",
                    "enabled": False,
                }
            )
            continue

        run_folder = cfg.resolve_simulation_run_folder(simulation)
        committed_simulation = committed_simulation_rows.get(str(simulation.id), {})
        if run_folder is None:
            committed_run_folder = str(committed_simulation.get("run_folder", "")).strip()
            if committed_run_folder != "":
                run_folder = Path(committed_run_folder).expanduser()
                if not run_folder.is_absolute():
                    run_folder = (cfg.base_dir / run_folder).resolve()
        if run_folder is None:
            raise ValueError(
                f"Capability-gallery simulation comparison case '{config_path}' requires "
                f"a committed run_folder for simulation '{simulation.id}'."
            )
        if not run_folder.exists():
            raise FileNotFoundError(
                f"Missing run folder for simulation '{simulation.id}': {run_folder}"
            )

        rows = extract_observable_rows(
            comparison_id=str(section.comparison_id),
            simulation=simulation,
            run_folder=run_folder,
            observables=tuple(section.observable),
        )
        all_rows.extend(rows)
        simulation_summaries.append(
            {
                "id": simulation.id,
                "label": simulation.label or simulation.id,
                "status": str(committed_simulation.get("status", "reused")),
                "enabled": True,
                "solver": simulation.solver,
                "mesh_label": simulation.mesh_label,
                "mesh_mode": simulation.mesh_mode,
                "run_folder": str(run_folder),
                "wall_time_seconds": committed_simulation.get("wall_time_seconds"),
                "metrics": compact_run_metrics(read_json_file(run_folder / "_metrics.json")),
                "run_metadata": read_simulation_run_metadata(run_folder),
                "n_observable_rows": len(rows),
            }
        )

    reference_simulation = section.reference_simulation
    if reference_simulation is None:
        for summary in simulation_summaries:
            if summary.get("status") in {"completed", "reused"}:
                reference_simulation = str(summary.get("id"))
                break

    _align_single_snapshot_rows(all_rows)
    detail_metrics, summary_metrics = build_comparison_metrics(
        all_rows,
        reference_simulation=reference_simulation,
    )

    manifest = {
        "schema_version": "comparison_manifest_v1",
        "comparison_id": section.comparison_id,
        "config_path": str(config_path),
        "run_simulations": section.run_simulations,
        "continue_on_error": section.continue_on_error,
        "reference_simulation": reference_simulation,
        "n_observable_rows": len(all_rows),
        "n_metric_rows": len(summary_metrics),
        "n_difference_rows": len(detail_metrics),
        "simulations": simulation_summaries,
        "observables": [observable.model_dump(mode="json") for observable in section.observable],
    }
    metrics_payload = {
        "schema_version": "comparison_metrics_v1",
        "comparison_id": section.comparison_id,
        "reference_simulation": reference_simulation,
        "summary": summary_metrics,
        "differences": detail_metrics,
    }
    return manifest, metrics_payload, all_rows


def _align_single_snapshot_rows(rows: list[dict[str, Any]]) -> None:
    """Align snapshot-only observables across simulations even when time indices differ."""

    snapshot_keys: dict[tuple[str, str], set[str]] = {}
    for row in rows:
        key = (str(row.get("observable", "")), str(row.get("simulation_id", "")))
        snapshot_keys.setdefault(key, set()).add(str(row.get("comparison_time_key", "")))

    aligned_observables = {
        observable
        for observable, _simulation in snapshot_keys
        if observable
        and all(len(keys) == 1 for (obs, _), keys in snapshot_keys.items() if obs == observable)
    }
    for row in rows:
        observable = str(row.get("observable", ""))
        if observable in aligned_observables:
            row["comparison_time_key"] = f"snapshot:{observable}"


def _sample_scatter_indices(size: int, *, max_points: int = 3000) -> np.ndarray:
    if size <= max_points:
        return np.arange(size, dtype=int)
    return np.linspace(0, size - 1, num=max_points, dtype=int)


def _render_simulation_comparison_figure(
    *,
    figure_path: Path,
    case_title: str,
    focus_simulation_label: str,
    reference_simulation_label: str,
    summary_rows: list[dict[str, Any]],
    detail_rows: list[dict[str, Any]],
) -> None:
    plt = _import_pyplot()

    observable_order = [str(row["observable"]) for row in summary_rows]
    grouped_detail: dict[str, list[dict[str, Any]]] = {
        observable: [row for row in detail_rows if str(row.get("observable", "")) == observable]
        for observable in observable_order
    }

    figure_path.parent.mkdir(parents=True, exist_ok=True)
    fig = plt.figure(figsize=(14.0, 8.8), dpi=140)
    gs = fig.add_gridspec(2, 2, height_ratios=[1.15, 0.85])
    ax_left = fig.add_subplot(gs[0, 0])
    ax_right = fig.add_subplot(gs[0, 1])
    ax_bar = fig.add_subplot(gs[1, :])

    scatter_axes = [ax_left, ax_right]
    for ax, observable in zip(scatter_axes, observable_order[:2], strict=False):
        rows = grouped_detail.get(observable, [])
        reference_values = np.asarray(
            [float(row["reference_value"]) for row in rows],
            dtype=float,
        )
        simulation_values = np.asarray(
            [float(row["value"]) for row in rows],
            dtype=float,
        )
        sample_index = _sample_scatter_indices(reference_values.size)
        sampled_reference = reference_values[sample_index]
        sampled_simulation = simulation_values[sample_index]
        low = float(np.nanmin(np.concatenate([sampled_reference, sampled_simulation])))
        high = float(np.nanmax(np.concatenate([sampled_reference, sampled_simulation])))
        ax.scatter(
            sampled_reference,
            sampled_simulation,
            s=8,
            alpha=0.30,
            color="#1f77b4",
            edgecolors="none",
        )
        ax.plot([low, high], [low, high], linestyle="--", color="0.35", linewidth=1.0)
        summary_row = next(row for row in summary_rows if str(row["observable"]) == observable)
        unit = str(summary_row.get("unit", "")).strip()
        ax.set_title(
            f"{_humanize_case_token(observable)}\n"
            f"RMSE {float(summary_row['rmse']):.4g} {unit}, "
            f"MAE {float(summary_row['mae']):.4g} {unit}".strip()
        )
        ax.set_xlabel(f"{reference_simulation_label} [{unit}]".strip())
        ax.set_ylabel(f"{focus_simulation_label} [{unit}]".strip())
        ax.grid(True, alpha=0.25)

    if len(observable_order) < 2:
        ax_right.axis("off")
        if observable_order:
            only_summary = summary_rows[0]
            ax_right.text(
                0.02,
                0.98,
                "\n".join(
                    [
                        f"Reference: {reference_simulation_label}",
                        f"Candidate: {focus_simulation_label}",
                        f"Observable: {_humanize_case_token(str(only_summary['observable']))}",
                        f"Matched value pairs: {int(only_summary['n_pairs'])}",
                        f"Bias: {float(only_summary['bias']):.4g} {only_summary['unit']}",
                        f"Max abs. error: {float(only_summary['max_abs_error']):.4g} {only_summary['unit']}",
                    ]
                ),
                transform=ax_right.transAxes,
                ha="left",
                va="top",
                family="monospace",
                fontsize=10.0,
                bbox={"boxstyle": "round,pad=0.5", "fc": "#f7f7f7", "ec": "0.75"},
            )

    x = np.arange(len(summary_rows), dtype=float)
    mae_values = np.asarray([float(row["mae"]) for row in summary_rows], dtype=float)
    rmse_values = np.asarray([float(row["rmse"]) for row in summary_rows], dtype=float)
    ax_bar.bar(x - 0.18, mae_values, width=0.34, label="MAE", color="#1f77b4")
    ax_bar.bar(x + 0.18, rmse_values, width=0.34, label="RMSE", color="#ff7f0e")
    ax_bar.set_xticks(x)
    ax_bar.set_xticklabels([_humanize_case_token(str(row["observable"])) for row in summary_rows])
    ax_bar.set_ylabel("Error [m]")
    ax_bar.set_title("Map-wide error summary")
    ax_bar.grid(True, axis="y", alpha=0.25)
    ax_bar.legend()

    fig.suptitle(
        f"{case_title}: {focus_simulation_label} vs {reference_simulation_label}",
        fontsize=14,
    )
    fig.tight_layout(rect=[0, 0, 1, 0.96])
    fig.savefig(figure_path, bbox_inches="tight")
    plt.close(fig)


