"""Generate hydromodpy/display/figure_table.py by inspecting every figure class."""

from __future__ import annotations

import importlib
import inspect
import pkgutil
import shutil
import subprocess
import sys
from pathlib import Path

from hydromodpy.display.figure import BaseFigure, option_names_of, options_of

TARGET_REL_PATH = Path("hydromodpy/display/figure_table.py")


def collect_figure_data() -> tuple[
    dict[str, str],
    dict[str, str],
    dict[str, tuple[str, ...]],
    dict[str, tuple[str, ...]],
]:
    """Collect (figures, former_names, options, python_only_options) from figure classes."""
    pkg = importlib.import_module("hydromodpy.display.figures")
    figures: dict[str, str] = {}
    former_names: dict[str, str] = {}
    options: dict[str, tuple[str, ...]] = {}
    python_only_options: dict[str, tuple[str, ...]] = {}

    for info in pkgutil.iter_modules(pkg.__path__):
        if info.name.startswith("_"):
            continue
        mod = importlib.import_module(f"{pkg.__name__}.{info.name}")
        for _, cls in inspect.getmembers(mod, inspect.isclass):
            if (
                cls.__module__ == mod.__name__
                and issubclass(cls, BaseFigure)
                and "spec" in cls.__dict__
            ):
                name = cls.spec.name
                figures[name] = f"{cls.__module__}:{cls.__qualname__}"
                for former in cls.spec.former_names:
                    former_names[former] = name
                options[name] = tuple(sorted(option_names_of(cls)))
                py_opts = tuple(sorted(opt.name for opt in options_of(cls) if opt.python_only))
                if py_opts:
                    python_only_options[name] = py_opts

    return figures, former_names, options, python_only_options


def generate_figure_table_source() -> str:
    """Return the ruff-formatted Python source code for figure_table.py."""
    figures, former_names, options, python_only_options = collect_figure_data()

    lines = [
        '"""Table of figure implementations, generated by tools.figure_table.',
        "",
        "Do not edit by hand; run: python -m tools.figure_table",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "FIGURES: dict[str, str] = {",
    ]
    for k in sorted(figures):
        lines.append(f'    "{k}": "{figures[k]}",')
    lines.append("}")
    lines.append("")
    lines.append("FORMER_NAMES: dict[str, str] = {")
    for k in sorted(former_names):
        lines.append(f'    "{k}": "{former_names[k]}",')
    lines.append("}")
    lines.append("")
    lines.append("OPTIONS: dict[str, tuple[str, ...]] = {")
    for k in sorted(options):
        opts_str = ", ".join(f'"{o}"' for o in options[k])
        if len(options[k]) == 1:
            opts_str += ","
        lines.append(f'    "{k}": ({opts_str}),')
    lines.append("}")
    lines.append("")
    lines.append("PYTHON_ONLY_OPTIONS: dict[str, tuple[str, ...]] = {")
    for k in sorted(python_only_options):
        opts_str = ", ".join(f'"{o}"' for o in python_only_options[k])
        if len(python_only_options[k]) == 1:
            opts_str += ","
        lines.append(f'    "{k}": ({opts_str}),')
    lines.append("}")
    lines.append("")

    raw_code = "\n".join(lines)
    ruff_bin = shutil.which("ruff") or "/home/bb/micromamba/envs/hmp_dev/bin/ruff"
    res = subprocess.run(
        [ruff_bin, "format", "-"],
        input=raw_code,
        text=True,
        capture_output=True,
        check=True,
    )
    return res.stdout


def main() -> None:
    source = generate_figure_table_source()
    repo_root = Path(__file__).resolve().parent.parent
    target = repo_root / TARGET_REL_PATH
    target.write_text(source, encoding="utf-8")
    print(f"Generated {target}")


if __name__ == "__main__":
    main()
