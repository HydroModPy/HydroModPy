def returns_html(v: dict, b, doc: str) -> str:
    if not v["returns"]:
        # No documented class or alias: the type line of the docstring, else the
        # annotation as written, else a pointer to the page.
        text = v.get("returns_doc") or ""
        ann = v.get("annotation", "")
        if not text and ann not in ("", "Any"):
            text = ann
        if text:
            return f"<code>{esc(text)}</code>"
        return '<span class="hmp-muted">see the function page</span>'
    parts = []
    for r in v["returns"]:
        if "qualname" in r:
            parts.append(
                f'<a href="{esc(H.doc_uri(b, doc, class_doc(r["name"])))}"><code>{esc(r["name"])}</code></a>'
            )
        else:
            parts.append(
                f'<code title="{esc(r["alias"])}">{esc(r["name"])}</code> <span class="hmp-muted">({esc(r["alias"])})</span>'
            )
    return ", ".join(parts)


def type_aliases_html(v: dict) -> str:
    """The aliases a signature names (``ConfigLike``...) with what each one stands for.

    An alias that the Returns row already spells out is not repeated.
    """
    shown = {r["name"] for r in v["returns"] if "alias" in r}
    items = [a for a in v.get("type_aliases", []) if a["name"] not in shown]
    return ", ".join(
        f'<code title="{esc(a["alias"])}">{esc(a["name"])}</code> '
        f'<span class="hmp-muted">({esc(a["alias"])})</span>'
        for a in items
    )


def users_html(verb: str, b, doc: str) -> str:
    users = cli_users_of(verb)
    if not users:
        return '<span class="hmp-muted">Python only</span>'
    return ", ".join(
        f'<a href="{esc(H.doc_uri(b, doc, command_doc(c)))}"><code>hmp {esc(c)}</code></a>'
        for c in users
    )


def exit_chip(b, doc: str, code: int) -> str:
    names = {e["code"]: e["name"] for e in A.get("exit_codes", [])}
    label = names.get(code, "").removeprefix("EXIT_").lower().replace("_", " ")
    href = H.doc_uri(b, doc, f"{CLI}/exit-codes") + f"#exit-{code}"
    title = f' title="{esc(label)}"' if label else ""
    return f'<a class="hmp-chip hmp-chip-exit" href="{esc(href)}"{title}>{code}</a>'


def group_id(title: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")


def code_key(code: str | None) -> int:
    m = re.search(r"E(\d+)$", code or "")
    return int(m.group(1)) if m else 0


