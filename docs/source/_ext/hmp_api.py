def args_table(arguments: list[dict], skip: set[str], b=None, doc: str = "") -> str:
    rows = []
    for a in arguments:
        if skip and a["flags"][0] in skip:
            continue
        if not a["positional"] and flag_key(a) in SHARED:
            continue
        flags = ", ".join(f"<code>{esc(f)}</code>" for f in a["flags"])
        if a.get("metavar"):
            flags += f" <code class='hmp-muted'>{esc(a['metavar'])}</code>"
        extra = []
        if a.get("choices"):
            extra.append("one of " + " | ".join(f"<code>{esc(x)}</code>" for x in a["choices"]))
        if (
            a.get("default") not in (None, "False", "None", "[]")
            and "default" not in (a.get("help") or "").lower()
        ):
            extra.append(f"default <code>{esc(a['default'])}</code>")
        if a.get("required") and not a["positional"]:
            extra.append('<span class="tc tc-req">required</span>')
        if b is not None:
            for flag in a["flags"]:
                if flag in FLAG_LINKS:
                    target, label = FLAG_LINKS[flag]
                    extra.append(f'<a href="{esc(H.doc_uri(b, doc, target))}">{esc(label)}</a>')
        helptext = esc(a.get("help") or "") or '<span class="hmp-muted">-</span>'
        rows.append(f"<tr><td>{flags}</td><td>{helptext} {' · '.join(extra)}</td></tr>")
    if not rows:
        return ""
    return (
        '<table class="api-t api-args"><thead><tr><th>Argument</th><th>What it does</th></tr></thead><tbody>'
        + "".join(rows)
        + "</tbody></table>"
    )


def shared_note(c: dict, b, doc: str) -> str:
    """One line naming the shared options this command also takes."""
    flags = [
        a["flags"][-1] for a in c["arguments"] if not a["positional"] and flag_key(a) in SHARED
    ]
    if not flags:
        return ""
    href = H.doc_uri(b, doc, f"{CLI}/index") + "#shared-options"
    chips = " ".join(f"<code>{esc(f)}</code>" for f in flags)
    return (
        f'<p class="hmp-muted">Also takes the <a href="{esc(href)}">shared options</a> {chips}.</p>'
    )


EXAMPLE_HEAD = re.compile(r"^(Examples?):\s*$")


def epilog_html(text: str) -> str:
    """Render the Example section of a help epilog as a titled terminal block."""
    blocks: list[str] = []
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        m = EXAMPLE_HEAD.match(lines[i])
        if m:
            cmds = []
            i += 1
            while i < len(lines) and (lines[i].startswith(" ") or not lines[i].strip()):
                if lines[i].strip():
                    cmds.append(lines[i].strip())
                i += 1
            body = "\n".join(f'<span class="cmd">$ {esc(c)}</span>' for c in cmds)
            blocks.append(
                f'<p class="hmp-cli-h">{m.group(1)}</p><pre class="hmp-term cli-example">{body}</pre>'
            )
        elif lines[i].strip():
            para = [lines[i].strip()]
            i += 1
            while i < len(lines) and lines[i].strip() and not EXAMPLE_HEAD.match(lines[i]):
                para.append(lines[i].strip())
                i += 1
            blocks.append(f"<p>{esc(' '.join(para))}</p>")
        else:
            i += 1
    return "".join(blocks)


def exit_codes_of(path: list[str]) -> dict:
    """The exit codes the command sets itself; a subcommand without its own entry uses its parent's."""
    table = A.get("command_exit_codes", {})
    for n in range(len(path), 1, -1):
        entry = table.get(" ".join(path[:n]))
        if entry is not None:
            return entry
    return {"codes": [], "mapped": False}


def exit_line(path: list[str], b, doc: str) -> str:
    entry = exit_codes_of(path)
    codes = [c for c in entry["codes"] if c != 0]
    if not codes and not entry["mapped"]:
        return ""
    link = H.doc_uri(b, doc, f"{CLI}/exit-codes")
    parts = []
    if codes:
        parts.append(
            "Exit codes it sets itself: " + " ".join(exit_chip(b, doc, c) for c in codes) + "."
        )
    if entry["mapped"]:
        parts.append("An exception it does not catch ends with the code of its class.")
    parts.append(f'<a href="{esc(link)}">All exit codes</a>.')
    return f'<p class="hmp-muted hmp-exit-line">{" ".join(parts)}</p>'


class CommandDirective(SphinxDirective):
    required_arguments = 1
    final_argument_whitespace = True
    option_spec = {"skip": directives.unchanged}

    def run(self):
        path = self.arguments[0].split()
        skip = set((self.options.get("skip") or "").split())
        c = command(path)
        if not c:
            logger.warning(f"[hmp] unknown command {' '.join(path)}", location=self.get_location())
            return []
        b, doc = H.current_builder(), self.env.docname
        parts = [
            f'<pre class="hmp-term cli-usage"><span class="cmd">$ {esc(c["usage"])}</span></pre>'
        ]
        if c["description"]:
            parts.append(f"<p>{esc(c['description'])}</p>")
        if c["subcommands"]:

            def target(name: str) -> str:
                # A top-level command has a page; a deeper one is a section of it,
                # whose id is its words joined by dashes.
                if len(path) == 1:
                    return H.doc_uri(b, doc, command_doc(name))
                return H.doc_uri(b, doc, command_doc(path[1])) + "#" + "-".join(path + [name])

            rows = "".join(
                f'<tr><td><a href="{esc(target(s["name"]))}"><code>{esc(" ".join(path + [s["name"]]))}</code></a></td>'
                f"<td>{esc(s.get('help') or '')}</td></tr>"
                for s in c["subcommands"]
            )
            parts.append(
                f'<table class="api-t"><thead><tr><th>Command</th><th>What it does</th></tr></thead><tbody>{rows}</tbody></table>'
            )
        parts.append(args_table(c["arguments"], skip, b, doc))
        if len(path) > 1:
            parts.append(shared_note(c, b, doc))
        if c["epilog"]:
            parts.append(epilog_html(c["epilog"]))
        if not c["subcommands"]:
            parts.append(exit_line(path, b, doc))
        return [H.raw("".join(parts))]


