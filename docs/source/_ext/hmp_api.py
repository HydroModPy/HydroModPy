class GapsDirective(SphinxDirective):
    """Docstring and help-string coverage. For the contributor pages, not the public reference."""

    def run(self):
        verbs = A.get("verbs", [])
        items = []
        for sec in ("Parameters", "Returns", "Examples"):
            missing = [v["name"] for v in verbs if sec not in v["sections"]]
            if missing:
                items.append(
                    f"<li>{len(missing)} function(s) without a <b>{esc(sec)}</b> section: {', '.join(f'<code>{esc(x)}</code>' for x in missing)}</li>"
                )
        nodoc = [c["name"] for c in classes("result", "engine") if not c["summary"]]
        if nodoc:
            items.append(
                f"<li>{len(nodoc)} class(es) without a docstring: {', '.join(f'<code>{esc(x)}</code>' for x in nodoc)}</li>"
            )
        undoc = sum(
            1
            for c in classes("result")
            for m in c.get("members", [])
            if m["kind"] != "attribute" and not m["summary"]
        )
        if undoc:
            items.append(
                f"<li>Methods or properties of the returned objects without a docstring: {undoc}</li>"
            )
        mods = [m["name"] for m in A.get("modules", []) if not m["summary"]]
        if mods:
            items.append(
                f"<li>{len(mods)} module(s) without a docstring: {', '.join(f'<code>{esc(x)}</code>' for x in mods)}</li>"
            )
        nohelp = sum(1 for c in A.get("commands", []) for a in c["arguments"] if not a["help"])
        if nohelp:
            items.append(f"<li>{nohelp} command-line argument(s) without a help string</li>")
        if not items:
            return []
        return [
            H.raw(
                f'<div class="hmp-links"><div class="hmp-links-h">Gaps in the docstrings and help strings</div><ul>{"".join(items)}</ul></div>'
            )
        ]


class StabilityDirective(SphinxDirective):
    """What the names of ``hydromodpy.__all__`` promise, from the version and the release policy."""

    def run(self):
        b, doc = H.current_builder(), self.env.docname
        version = A.get("version", "")
        names = A.get("all_names", [])
        verbs = len(A.get("verbs", []))
        helpers = len(A.get("helpers", []))
        n_classes = len(classes("result", "engine", "config"))
        n_classes -= sum(1 for c in classes("result", "engine", "config") if c.get("outside_all"))
        mods = len(A.get("modules", []))
        rest = len(names) - verbs - helpers - n_classes - mods
        counts = f"{verbs + helpers} functions, {n_classes} classes, {mods} modules" + (
            f" and {rest} other names" if rest > 0 else ""
        )
        policy = H.doc_uri(b, doc, "about/versions")
        m = re.search(r"(a|b|rc)\d+$", version)
        stage = {
            "a": "This is an alpha release: the API, the configuration, the storage and the behavior "
            "can still change from one alpha to the next, and a name listed here can be renamed or removed.",
            "b": "This is a beta release: the public contract changes only to fix a release blocker.",
            "rc": "This is a release candidate: only release-blocking fixes land.",
        }.get(
            m.group(1) if m else "",
            "This is a final release: a rename or a removal waits for the next major version.",
        )
        text = (
            f"<p>This page documents <code>hydromodpy {esc(version)}</code>. The public surface is the "
            f"{len(names)} names of <code>hydromodpy.__all__</code> ({counts}), the classes they return, "
            "and the exceptions of this reference. A name outside this reference is internal, and so are "
            "the <code>hydromodpy._api</code> module and the <code>hydromodpy.cli._workers</code> package.</p>"
            f"<p>{esc(stage)} Versions follow semantic versioning with PEP 440 pre-release tags, "
            f'and no compatibility shim is kept for a removed name: see the <a href="{esc(policy)}">release policy</a>.</p>'
        )
        return [H.raw(f'<div class="hmp-note hmp-stability">{text}</div>')]


class RelationsDirective(SphinxDirective):
    """The result objects, what each is and which calls hand it to you."""

    def run(self):
        b, doc = H.current_builder(), self.env.docname
        produced = A.get("produced_by", {})
        by_name = {c["name"]: c for c in classes("result")}
        order = ["Catalog", "Run", "RunSet", "GlobalIndex", "Project"]
        order += [n for n in by_name if n not in order]
        rows = []
        for name in order:
            c = by_name.get(name)
            if c is None:
                continue
            calls = []
            for p in produced.get(name, []):
                if p["owner"]:
                    owner = by_name.get(p["owner"])
                    method = p["call"].split(".", 1)[1].removesuffix("()")
                    anchor = f"#{owner['qualname']}.{method}" if owner else ""
                    href = H.doc_uri(b, doc, class_doc(p["owner"])) + anchor
                else:
                    verb = p["call"].removeprefix("hmp.").removesuffix("()")
                    href = H.doc_uri(b, doc, verb_doc(verb))
                calls.append(f'<a href="{esc(href)}"><code>{esc(p["call"])}</code></a>')
            rows.append(
                f'<tr><td><a href="{esc(H.doc_uri(b, doc, class_doc(name)))}"><code>{esc(name)}</code></a></td>'
                f"<td>{H.inline_md(c['summary'], b, doc)}</td>"
                f"<td>{', '.join(calls) or '<span class=hmp-muted>built by the other objects</span>'}</td></tr>"
            )
        return [
            H.raw(
                '<div class="hmp-matrix-wrap"><table class="api-t"><thead><tr><th>Object</th><th>What it is</th>'
                f"<th>You get it from</th></tr></thead><tbody>{''.join(rows)}</tbody></table></div>"
            )
        ]


