class ExceptionTreeDirective(SphinxDirective):
    """The hierarchy of the exceptions defined in ``hydromodpy.core.exceptions``."""

    def run(self):
        excs = [e for e in A.get("exceptions", []) if e["module"] == "hydromodpy.core.exceptions"]
        children: dict[str | None, list[dict]] = {}
        for e in excs:
            children.setdefault(e["parent"], []).append(e)

        def render(e: dict) -> str:
            code = f" {chip(esc(e['code']), 'hmp-chip-code')}" if e["code"] else ""
            kids = children.get(e["name"], [])
            sub = "<ul>" + "".join(render(k) for k in kids) + "</ul>" if kids else ""
            return f'<li><a href="#exc-{esc(e["name"])}"><code>{esc(e["name"])}</code></a>{code}{sub}</li>'

        roots = children.get(None, [])
        return [H.raw('<ul class="hmp-tree">' + "".join(render(r) for r in roots) + "</ul>")]


