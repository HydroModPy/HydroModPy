# A command-line option held by at least this many commands is documented once.
SHARED_MIN = 3


def esc(text) -> str:
    return html.escape(str(text), quote=True)


def flag_key(a: dict) -> tuple:
    return (tuple(a["flags"]), a.get("help") or "")


def load(srcdir: Path) -> None:
    path = srcdir / "_data/api.json"
    A.clear()
    SHARED.clear()
    if path.exists():
        A.update(json.loads(path.read_text()))
    seen: dict[tuple, list[str]] = {}
    for c in A.get("commands", []):
        for a in c["arguments"]:
            if not a["positional"] and a.get("help"):
                seen.setdefault(flag_key(a), []).append(" ".join(c["path"][1:]))
    SHARED.update({k: v for k, v in seen.items() if len(v) >= SHARED_MIN})


def verb_doc(name: str) -> str:
    return f"{PY}/hmp-{name}"


def class_doc(name: str) -> str:
    return f"{PY}/{name}"


def command_doc(top: str) -> str:
    return f"{CLI}/{top}"


def classes(*kinds: str) -> list[dict]:
    return [c for c in A.get("classes", []) if c["kind"] in kinds]


def cli_users_of(verb: str) -> list[str]:
    return [cmd for cmd, verbs in A.get("cli_to_verbs", {}).items() if verb in verbs]


def command(path: list[str]) -> dict:
    return next((c for c in A.get("commands", []) if c["path"] == path), {})


def chip(text: str, cls: str = "") -> str:
    return f'<span class="hmp-chip {cls}">{text}</span>'


# ---------------------------------------------------------------- source links


@cache
def built_commit() -> str:
    """The commit the site is built from: the CI variable, else the checkout's HEAD."""
    for key in ("HMP_DOCS_COMMIT", "GITHUB_SHA"):
        if os.environ.get(key):
            return os.environ[key]
    try:
        out = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
            timeout=15,
            check=True,
        )
        return out.stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return "main"


def source_url(rel_path: str, first: int | None = None, last: int | None = None) -> str:
    """Link to a file of the repository at the built commit, with an optional line range."""
    url = f"{REPO_URL}/blob/{built_commit()}/{rel_path}"
    if first:
        url += f"#L{first}" + (f"-L{last}" if last and last != first else "")
    return url


def linkcode_resolve(domain: str, info: dict) -> str | None:
    """Where the source of a documented Python object lives on GitHub.

    Called by ``sphinx.ext.linkcode`` for each entry autodoc renders. Returns
    None for an object defined outside the repository, or one that has no
    source file (a built-in, an alias to a C function).
    """
    if domain != "py" or not info.get("module"):
        return None
    try:
        obj = import_module(info["module"])
        for part in info["fullname"].split("."):
            obj = getattr(obj, part)
    except Exception:
        return None
    if isinstance(obj, property):
        obj = obj.fget
    try:
        obj = inspect.unwrap(getattr(obj, "__func__", obj))
        file = Path(inspect.getsourcefile(obj) or "").resolve()
        lines, first = inspect.getsourcelines(obj)
        rel = file.relative_to(REPO_ROOT)
    except (TypeError, OSError, ValueError):
        return None
    return source_url(rel.as_posix(), first, first + len(lines) - 1)


def on_config_inited(app, config) -> None:
    """Use ``linkcode_resolve`` of this module unless ``conf.py`` defines its own."""
    if getattr(config, "linkcode_resolve", None) is None:
        config.linkcode_resolve = linkcode_resolve


